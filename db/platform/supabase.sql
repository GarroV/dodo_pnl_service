-- Платформу хранения ещё не выбрали. Этот файл — вся специфика Supabase,
-- какая есть: личность пользователя берётся из его Auth. Если победит другой
-- вариант (управляемый Postgres, Neon, свой сервер) — меняется только этот
-- файл, схема и код не трогаются.
--
-- Применять ДО миграций.
-- =============================================================================

create or replace function app_user_id()
returns uuid
language sql stable
set search_path = public
as $$
    select auth.uid()
$$;

comment on function app_user_id() is
    'Единственная точка привязки к платформе аутентификации. Здесь — Supabase Auth';

