"""Какие внешние данные партнёр берёт в работу, а какие только смотрит (D063).

Коннектор к чужой системе — это не «включили и поехали». Часть чужих цифр может
считаться не так, как нужно партнёру: владелец прямо сомневается в
себестоимости Dodo IS. Проверяется это только на живом месяце, а проверять
цифру, которая уже попала в расчёт, поздно.

Отсюда три состояния у каждого потока (`off` / `trial` / `on`) и **одно место,
где решается вопрос «идёт ли это в расчёт»** — функция `trusted`. Разнести
проверку по местам потребления значило бы получить продукт, где один экран
считает поток включённым, а другой нет.

Правило простое и должно таким остаться: **в расчёт и в P&L идёт только `on`.**
`trial` существует ровно для того, чтобы цифру можно было увидеть, не пуская её
в итоги.
"""
from __future__ import annotations

from uuid import UUID

from .models import DataFeed

__all__ = ["FEEDS", "OFF", "TRIAL", "ON", "state", "trusted", "pulled", "trusted_sources"]

OFF = "off"
TRIAL = "trial"
ON = "on"

# Потоки, которые продукт знает. Список тот же, что в enum `data_feed`
# (миграция 0260) — база отвергнет чужое значение, здесь он для показа и
# перебора.
FEEDS: dict[str, str] = {
    "hours": "отработанные часы",
    "revenue": "выручка по точкам",
    "cogs": "расход сырья и себестоимость",
    "write_offs": "списания, брак, питание персонала",
    "staff": "справочник сотрудников",
    "units": "справочник точек",
}

# Какой поток отвечает за данные с этой пометкой источника. Пометка стоит у
# строки табеля и у факта (`source`), а состояние — у потока: без этой связи
# пришлось бы держать состояние у каждой строки, то есть отвечать на вопрос
# «доверяем ли» при каждой записи, а не один раз.
FEED_BY_SOURCE: dict[str, str] = {
    "dodo_is": "hours",
}


def state(tenant_id: UUID, feed: str) -> str:
    """Состояние потока у партнёра. Строки нет — поток выключен.

    Отсутствие строки должно означать именно «выключено», а не «неизвестно»:
    поток, о котором никто не знает, не должен молча попадать в отчёт.
    """
    if feed not in FEEDS:
        raise ValueError(f"неизвестный поток данных: {feed}")
    found = (
        DataFeed.objects.filter(tenant_id=tenant_id, feed=feed)
        .values_list("state", flat=True)
        .first()
    )
    return found or OFF


def trusted(tenant_id: UUID, feed: str) -> bool:
    """Идут ли данные этого потока в расчёт и в P&L.

    Единственное место, где этот вопрос решается. `trial` отвечает «нет»
    намеренно: он для того и заведён, чтобы цифру было видно, но она ни на один
    итог не влияла.
    """
    return state(tenant_id, feed) == ON


def pulled(tenant_id: UUID, feed: str) -> list[str]:
    """Пометки источников, которые сейчас можно пускать в расчёт.

    Возвращает то, чем помечены строки (`source`), а не имена потоков: у места
    потребления на руках именно пометка. `manual` и `import` в списке всегда —
    это данные, которые ввёл человек продукта, и внешним состоянием они не
    управляются.
    """
    always = ["manual", "import", "spread"]
    return always + [
        source for source, name in FEED_BY_SOURCE.items()
        if name == feed and trusted(tenant_id, feed)
    ]


def trusted_sources(tenant_id: UUID) -> list[str]:
    """Все пометки источников, которым партнёр доверяет расчёт.

    Для мест, где строки разных потоков лежат вперемешку — как в табеле, куда
    часы приходят и руками, и загрузкой, и коннектором.
    """
    sources = {"manual", "import", "spread"}
    for source, feed in FEED_BY_SOURCE.items():
        if trusted(tenant_id, feed):
            sources.add(source)
    return sorted(sources)
