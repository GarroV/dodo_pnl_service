"""Отсутствие итога больше никого не называет (T071).

**Что течёт.** Суммы вынесены в `payslip_totals` (T050), набор регистров строки
закрыт привилегией (T065) — а сама строка `payslips` видна всем в тенанте, это
её работа: на ней держится ведомость по компонентам. Значит **дырка в
производной таблице и есть сообщение**. Ролью `app_user` под бухгалтером

    select e.last_name
      from payslips p
      join employees e on e.id = p.employee_id
      left join payslip_totals t on t.payslip_id = p.id
     where t.payslip_id is null

отдавал 27 фамилий из 35 — поимённо тех, у кого есть выплаты в закрытых от неё
регистрах. Чисел нет, но D023 требует «ни строк, ни следа».

**Вторая дырка той же формы, найденная по дороге.** Функция
`app_payslip_ledgers_visible(uuid)` из миграции `0021` — `security definer` и,
как всякая функция по умолчанию, исполнима кем угодно. Под бухгалтером

    select p.id, app_payslip_ledgers_visible(p.id) from payslips p

отвечал `false` ровно на тех строках, где есть скрытый регистр. То есть закрытую
колонку выдавала функция, заведённая, чтобы её закрыть. Проверено на живой базе
до правки. Чинить это отзывом `execute` бессмысленно: пока признак вычисляется
по строке, он остаётся признаком строки.

**Почему прятать саму строку ведомости нельзя — обе формы проверены и
отвергнуты.**

* `ledgers <@ видимые` (подмножество) — ровно то, на чём обожглись в T050:
  ведомость собирается присоединением к `payslips`, и скрытая строка уносит
  **видимые официальные** компоненты смешанного сотрудника. Итог бухгалтера
  падает с 464 752,41 до 434 462,66, то есть ломает эталон приёмки.
* `ledgers && видимые` (пересечение) — суммы не двигаются, но вектор не
  закрывается: у смешанного сотрудника строка видна, а итога нет, и это тот же
  поимённый список.

Кроме того, ограничивающая политика на `payslips` ломает запись: политика
`for select` применяется и к `update`/`delete`, когда те читают колонки
(проверено — `delete ... where` по невидимой строке даёт `DELETE 0` **молча**),
а неполный набор регистров вдобавок **открывает** итоги (`'{}' <@ что угодно`).

**Корень глубже конкретного запроса.** Течёт не «этот left join», а то, что
**видимость производной строки зависит от её содержимого**. Пока зависит, любая
пара «строка видна всегда — производная видна не всегда» называет людей, и
закрытие одного запроса ничего не меняет.

**Что сделано.** Видимость итогов определяется **только ролью**: их видит тот,
кому видны все регистры вообще, и не видит никто другой — независимо от того,
что в строке. Тогда состояний ровно два: «итогов столько же, сколько строк
ведомости» и «итогов нет». Третьего, по которому кого-то опознают, не
существует. Функция `app_payslip_ledgers_visible()` за ненадобностью удалена
вместе со своим вектором.

**Почему «все значения типа», а не «все три».** Набор берётся из `enum_range`,
а не списком: если в `ledger` появится четвёртое значение, роли, видевшие три,
итоги потеряют. Это неудобно и это правильная сторона ошибки — новый регистр не
должен открываться сам собой тем, кому его не давали.

**Цена, которую надо знать.** Бухгалтер перестаёт видеть сохранённые итоги
вовсе, включая полностью официальные строки (раньше видела 8 из 35 — и это как
раз и был тот самый список). Её экран не меняется: ведомость собирается из
`pay_components`, а `payslip_totals` в продукте сегодня не читает никто, пишет
только расчёт. Чтобы у бухгалтера были бруто и налоги по официальному регистру,
итоги надо раскладывать по регистрам, а как делить взносы, посчитанные от общего
нето, у партнёра не выяснено — вопрос заведён issue, а не придуман здесь.

**Что остаётся у `payslips.ledgers`.** Колонка и триггер живут дальше, но
видимость больше не держат: читает её только сама база. Колонка закрыта от роли
приложения привилегией (T065), и это по-прежнему проверяется.
"""
from django.db import migrations

# Функция, а не выражение в политике: правило «роль видит все регистры вообще»
# должно быть в одном месте, иначе следующая таблица с итогами получит свою
# копию условия и разъедется с этой молча.
#
# `security definer` здесь не нужен: `app_visible_ledgers()` уже исполняется
# правами владельца, а больше эта функция ничего не читает. Лишний definer —
# лишняя поверхность, а мы как раз одну такую закрываем.
FUNCTION = """
create or replace function app_sees_every_ledger(p_tenant uuid)
returns boolean
language sql stable
set search_path = public
as $$
    select enum_range(null::ledger)::ledger[] <@ app_visible_ledgers(p_tenant)
$$;

comment on function app_sees_every_ledger(uuid) is
    'Видны ли пользователю ВСЕ регистры учёта в этом тенанте. На этом стоит видимость итогов расчёта: она свойство роли, а не строки (T071)';
"""

DROP_FUNCTION = "drop function if exists app_sees_every_ledger(uuid);"

POLICY = """
drop policy if exists ledger_visibility on payslip_totals;

create policy ledger_visibility on payslip_totals
    as restrictive for select
    using (app_sees_every_ledger(payslip_totals.tenant_id));

drop function if exists app_payslip_ledgers_visible(uuid);
"""

# Обратный ход возвращает прежнее устройство целиком, вместе с функцией: иначе
