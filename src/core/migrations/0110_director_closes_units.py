"""Закрывать часы точки вправе и оперативный директор (D033, T076).

**Что чинится.** Право `unit.close` (миграция `0031`, задача T022) было только у
управляющего точки. Значит месяц нельзя закрыть, пока управляющий в отпуске или
уволился, — при том что весь период директор утверждает и откатывает
(`period.approve`, `period.reopen`). Запрещать меньшее тому, кому разрешено
большее, — не разграничение доступа, а тупик в работе.

**Что здесь меняется и что нет.**

- Директор получает `unit.close`. Точек у него не задано (`memberships.unit_ids`
  пуст), поэтому политика видимости `unit_visibility` на `timesheet_closures`
  пропускает его к любой точке своего тенанта — и ровно к своему тенанту.
- Управляющий не меняется вовсе: право у него было и остаётся, а срез по своей
  точке держит та же политика видимости. Ни строки про него здесь нет
  специально — «у управляющего осталась только своя точка» это не новое
  правило, а то же самое, что действовало до задачи.
- Политики `0031` не трогаются. Право уже проверяется базой; менялся набор
  прав роли, а не механизм.

**Почему по коду роли, а не по набору прав.** «Кто ведёт месяц целиком» в данных
никак не записано: `period.approve` есть и у бухгалтера, а выдать ему закрытие
точек заодно значило бы решить за партнёра, что бухгалтер закрывает смены. Код
роли — единственный признак, который спека определяет прямо (четыре роли:
`director`, `accountant`, `manager`, `admin`). Партнёр, назвавший роль иначе,
правит права через экран ролей — это T018, и угадывать за него здесь нечего.

**Почему миграция, а не только сид.** Права ролей — данные, и в базе, которая уже
живёт, сид больше не гоняется. Без этой миграции право появилось бы лишь у тех,
кто пересоздаст демо-данные, а у остальных директор молча остался бы без кнопки.

**Почему в конце стоит проверка.** Таблица `roles` под `force row level
security`: роль, не обходящая политики, увидела бы отсюда ноль строк, и `update`
изменил бы ноль строк **молча** — миграция «прошла», право не появилось. Это тот
же корень, что у issue #44. Поэтому после правки проверяется результат, а не
факт выполнения оператора: не осталось ли роли `director` без права.
"""
from django.db import migrations

GRANT = """
update roles
   set permissions = permissions || '["unit.close"]'::jsonb
 where code = 'director'
   and not (permissions ? 'unit.close');

do $$
declare
    stuck int;
begin
    select count(*) into stuck
      from roles
     where code = 'director' and not (permissions ? 'unit.close');
    if stuck > 0 then
        raise exception
            'unit.close не доехал до % ролей директора: строки отрезаны политиками', stuck;
    end if;
end $$;
"""

