"""Роли спеки: что человек видит, где и что ему позволено (T140, issue #91).

Почему отдельным модулем. Ролей четыре, а списков было два: сид разработки
(`core.management.commands.seed_dev`) и сид демо (`demo.seed`). Оба описывали
одно и то же, и оба несли комментарий «набор регистров повторяет роли сида
разработки намеренно» — при том что у администратора сети они уже разъехались:
в продукте все три регистра, в демо один официальный. Разъезд нашли случайно и
по комментарию, а не по красному тесту: два списка одного и того же расходятся
молча.

Что здесь есть и чего нет. Здесь **форма** роли — регистры, точка, права: она
одна на продукт и на демо, потому что демо обязано показывать то, что партнёр
получит у себя, а не выдуманное. Названий ролей здесь нет: у продукта они
русские, у демо английские (D035, демо всегда англоязычно), и это не разъезд, а
замысел.

Живой базе то же самое приезжает миграциями (`0230`), а не отсюда: сид на
площадке не гоняется. Третьим списком это не делает — миграция описывает
конкретного партнёра, а не роль как таковую.
"""
from __future__ import annotations

from typing import NamedTuple

ALL_LEDGERS = ("official", "supplementary", "internal")

# Полный цикл месяца: ввод часов, расчёт, утверждение и всё, что нужно, чтобы
# исправить собственную ошибку, — откат с причиной, заморозка спорной строки,
# перенос разницы за закрытый месяц, закрытие часов точки.
MONTH_CYCLE = (
    "timesheet.edit", "payrun.calculate", "period.approve",
    "period.reopen", "payslip.freeze", "retro.post", "unit.close",
    # Разбор первички — часть ведения месяца, а не отдельная обязанность:
    # принесённая бумага становится строкой P&L того же периода, который эта
    # роль считает и утверждает (T174). Управляющему точки не даётся нарочно:
    # его роль донести бумагу, а не посчитать её. Наличные он вносит
    # по-прежнему — там он не классифицирует чужое, а вносит свою трату (T109).
    #
    # Администратору сети тоже не даётся, и это не забывчивость: его форма
    # намеренно не открывает данные расчёта («прав на них у него по-прежнему ни
    # одного»), а разобранная бумага — это именно данные расчёта.
    "suppliers.classify",
)


class RoleShape(NamedTuple):
    """Форма роли: регистры учёта, точка и права. Название — не здесь."""

    ledgers: tuple[str, ...]
    unit: str | None  # None — все точки тенанта
    permissions: tuple[str, ...]


ROLE_SHAPES: dict[str, RoleShape] = {
    # `payslip.freeze` — заморозка спорной строки ведомости (T027): её ставит
    # тот, кто ведёт месяц, а не управляющий точки. `retro.post` — перенос
    # разницы за закрытый месяц (T026), по тому же доводу. `unit.close` —
    # закрытие часов точки (D033, T076): у управляющего оно тоже есть, но
    # только на свою точку, а у директора точек не задано, то есть все. Без
    # этого закрыть месяц было некому, пока управляющий в отпуске, — при том
    # что весь период директор утверждает.
    "director": RoleShape(ALL_LEDGERS, None, MONTH_CYCLE),
    # Все три регистра и тот же набор прав, что у директора (D036, ответ
    # владельца на Q012). Раньше здесь стоял один официальный — догадка, что
    # «официальная роль не должна видеть остальное». У партнёра это сегодня не
    # так: бухгалтер и оперативный директор равны. Догадка стоила дорого:
    # расчёт периода — то, что спека требует от бухгалтера прямо, — не проходил
    # вовсе (база отвергает запись строк регистров, которых роль не видит), а
    # выгрузка P&L молча приходила без налогов и взносов.
    #
    # Механизм видимости при этом не разобран: он на месте и работает — у
    # управляющего точки набор по-прежнему неполный (D031), и политики режут ему
    # внутренний регистр. Сужать доступы будем позже, там где надо, — и механизм
    # к тому времени должен быть жив.
    "accountant": RoleShape(ALL_LEDGERS, None, MONTH_CYCLE),
    # Два регистра, а не один (D031): управляющий отвечает за свою точку и
    # должен видеть надбавки своей смены.
    "manager": RoleShape(
        ("official", "supplementary"), "NS1", ("timesheet.edit", "unit.close"),
    ),
    # Все три регистра, а не один официальный (T089, тот же довод, что в D033).
    # Справочники и правила ведёт он и только он: `directory.manage` и
    # `rules.manage` больше нет ни у кого. С одним официальным регистром это
    # давало тупик, а не разграничение: карточки курьеров и кухни он не видел
    # вовсе — админка показывала 8 сотрудников из 35 и 3 группы из 6, — то есть
    # **ни один пользователь продукта** не мог поменять курьеру ставку или
    # закрыть группу. Хуже того, число «8» подавалось без оговорок: узнать, что
    # есть ещё 27 карточек, было неоткуда.
    #
    # Запрещать меньшее тому, кому разрешено большее, — не разграничение, а
    # тупик в работе (D033). И «большее» здесь не фигура речи: `roles.manage`
    # означает, что администратор правит сами роли, то есть в любой момент
    # вправе выписать себе недостающий регистр.
    #
    # Данные расчёта это ему не открывает: прав на них у него по-прежнему ни
    # одного — ни считать, ни утверждать, ни править табель.
    "admin": RoleShape(
        ALL_LEDGERS, None, ("directory.manage", "rules.manage", "roles.manage"),
    ),
}

# Порядок ролей на экранах и в выводе сидов. Отдельно от словаря: словарь
# отвечает за форму роли, а порядок — за то, как их читает человек.
ROLE_ORDER = ("director", "accountant", "manager", "admin")
