"""
Кому демо открыто: один ответ на вопрос «эта дверь ведёт внутрь или в тупик».

Зачем отдельный модуль. Дверей в демо больше одной: титульная страница демо,
корень стенда и форма входа продукта (issue #116). Спрашивают они одно и то же —
включено ли демо и вправе ли этот посетитель туда войти, — и разъехавшиеся
ответы означают тупик: одна дверь пустила, вторая показала `404` или форму
пароля, которого у гостя нет. Поэтому правило записано один раз.

Почему не в `demo/views.py`, где оно раньше и жило. Спрашивает его теперь и
`web`, а `demo.views` импортирует `web.auth` — импорт в обратную сторону
замкнул бы кольцо. Здесь же нет ничего, кроме настроек: модуль можно звать из
любого места продукта.

Ключ по-прежнему спидбамп, а не секрет (см. `demo/views.py`): он спасает от
случайного прохожего и поисковика. Отсюда и главное свойство `reachable`:
посетителю без ключа дверь не **показывается**, а не «показывается и отвечает
отказом». Кнопка, ведущая в `404`, — тот же тупик, только по кнопке продукта.
"""
from __future__ import annotations

from django.conf import settings

__all__ = ["URL", "enabled", "grant", "key", "key_ok", "reachable", "remember_key"]

# Адрес титульной страницы демо. Строкой, а не `reverse("demo")`: маршруты демо
# подключаются только при `DEMO_MODE=1` (см. `config/urls.py`), и в продукте
# `reverse` упал бы — при том что спрашивают его как раз затем, чтобы узнать,
# показывать ли ссылку. Адрес один и тот же с `config/urls.py`; его сходимость
# держит `tests/test_demo_door.py`, который ходит по нему настоящим клиентом.
URL = "/demo/"

# Где лежит уже отданный ключ. Сессия, а не кука сама по себе: посетитель
# отдаёт ключ один раз ссылкой из письма, и таскать его в каждой ссылке внутри
# демо не должен.
SESSION_KEY = "demo_key"


def enabled() -> bool:
    """Включено ли демо на этом экземпляре. В продукте — нет."""
    return bool(getattr(settings, "DEMO_MODE", False))


def key() -> str:
    return (getattr(settings, "DEMO_KEY", "") or "").strip()


def key_ok(request) -> bool:
    """Спидбамп. Ключа не задано — открыто всем, и это осознанный режим."""
    wanted = key()
    if not wanted:
        return True
    if request.GET.get("key", "") == wanted:
        return True
    return request.session.get(SESSION_KEY) == wanted


def remember_key(request) -> None:
    """Запомнить отданный ключ, чтобы не спрашивать его на каждой странице."""
    wanted = key()
    if wanted and key_ok(request):
        request.session[SESSION_KEY] = wanted


def grant(request) -> None:
    """Положить ключ в сессию, не спрашивая его у посетителя.

    Нужно ровно в одном месте — при выходе из демо (issue #116). Выход чистит
    сессию, и ключ, отданный когда-то ссылкой, исчезал вместе с ней: гость
    оказывался на форме пароля без пути назад в демо, которое только что
    смотрел. Проверять `key_ok` здесь нельзя — сессия уже пуста, и проверка
    всегда отвечала бы «нет».

    Поэтому право на выдачу проверяет ВЫЗЫВАЮЩИЙ, до выхода: `reachable(...)`
    говорит, был ли этот посетитель внутри. Новым знанием ключ для него не
    становится — он у него уже был.
    """
    wanted = key()
    if wanted:
        request.session[SESSION_KEY] = wanted


def reachable(request) -> bool:
    """Ведёт ли дверь в демо внутрь — для ЭТОГО посетителя, а не вообще.

    Ровно этим вопросом решают, показывать ли путь в демо, и корень стенда, и
    форма входа. «Демо включено» одного мало: со включённым ключом посетитель
    без него получит `404`, и кнопка обманет.
    """
    return enabled() and key_ok(request)
