"""Раздел, который ведёт другая роль, — в демо не тупик, а переключатель (T163).

**Что было.** Кнопка «Enter the demo →» входит оперативным директором, а
справочники и правила ведёт администратор сети (`directory.manage` и
`rules.manage` есть только у него). Разделов, которых роль не ведёт, в шапке нет
вовсе — так решено осознанно (см. `web/templatetags/ui.py`, фильтр `may`): у
партнёра раздел, которого роль не ведёт, это нормальное устройство продукта, а
не пропавшая кнопка.

Для демо это решение даёт ровно обратное. Посетитель видит продукт впервые, ему
не с чем сравнить, и отсутствующий раздел он читает как отсутствующую
функциональность. Владелец, открыв демо, так и прочитал: «не вижу ни групп, ни
точек, ничего». Администратор сети при этом кнопкой на титульной странице даже
не показывался — то есть до справочников в демо нельзя было добраться **никакой**
ролью.

**Что делает этот модуль.** Отвечает на вопрос «кто ведёт этот раздел» и собирает
ссылку, которая переключает посетителя на ту роль и приводит его туда, куда он
шёл. Права продукта при этом не меняются ни на копейку: у партнёра
разграничение остаётся тем же, что было, — меняется только демо, где смысл
именно в том, чтобы показать продукт целиком.

**Почему не «выдать директору ведение справочников».** Это второй возможный ответ
на T163, и он про партнёра, а не про демо: он меняет то, кто у партнёра вправе
править ставки и правила расчёта. Такое решение принимает владелец, а не блок
стенда; в журнале блока оно записано вопросом.

**Роль ищется по форме, а не списком.** Кто что ведёт, уже записано в
`core.roles.ROLE_SHAPES`; список «раздел → роль» рядом с ним разъехался бы с ним
молча — ровно то, что уже случилось с двумя списками ролей (issue #91).
"""
from __future__ import annotations

from django.conf import settings
from django.urls import reverse
from django.utils.http import url_has_allowed_host_and_scheme, urlencode

from core.roles import ROLE_ORDER, ROLE_SHAPES

__all__ = ["offer", "safe_next", "who_manages"]


def who_manages(permission: str) -> str | None:
    """Код роли, которая ведёт раздел. None — такого права нет ни у кого.

    Порядок обхода — `ROLE_ORDER`, то есть порядок ролей на экранах: если право
    есть у нескольких ролей, посетителю предлагается первая из них, а не
    случайная. Сегодня и `directory.manage`, и `rules.manage` есть ровно у
    администратора сети, но полагаться на это нельзя — права партнёр правит сам.
    """
    for code in ROLE_ORDER:
        if permission in ROLE_SHAPES[code].permissions:
            return code
    return None


def safe_next(where: str) -> str | None:
    """Адрес внутри продукта или ничего.

    Проверка обязательна, хотя ссылку собирает сама шапка: адрес приезжает
    строкой запроса, то есть его может подставить кто угодно. Переход на чужой
    хост из демо был бы открытым перенаправлением — тем более неприятным, что
    ссылку на демо шлют в переписке и по ней ходят не глядя.
    """
    if not where or not where.startswith("/") or where.startswith("//"):
        return None
    if not url_has_allowed_host_and_scheme(where, allowed_hosts=None):
        return None
    return where


def offer(permission: str, url_name: str) -> dict | None:
    """Чем заменить пропавший раздел в демо. None — заменять нечем.

    Пусто в трёх случаях, и все три означают «показывать нечего»: демо
    выключено (в продукте этого механизма нет вовсе), права нет ни у одной роли,
    у роли нет названия в демо. Молчаливым отказом это не является: шапка в
    таком случае ведёт себя как раньше, то есть раздела просто нет — поведение
    продукта, а не поломка.
    """
    if not getattr(settings, "DEMO_MODE", False):
        return None
    code = who_manages(permission)
    if code is None:
        return None

    # Названия ролей в демо свои (английские, D035) — берутся оттуда, где живут,
    # а не переписываются здесь во второй раз.
    from .seed import ROLE_TITLES

    title = ROLE_TITLES.get(code)
    if not title:
        return None

    target = reverse(url_name)
    return {
        "url": reverse("demo-enter-as", args=[code]) + "?" + urlencode({"next": target}),
        "role": title,
        "target": target,
    }
