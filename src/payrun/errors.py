"""Отказы расчёта.

Отдельный модуль, чтобы выбор правил (`rules`) не зависел от расчёта (`calc`),
а сообщение было пригодно для показа человеку: расчёт отказывает по причинам,
которые исправляет пользователь, а не программист.
"""
from __future__ import annotations


class PayrunRefused(Exception):
    """Расчёт не выполнен, и причина понятна человеку.

    `http_status` — чем ответить в интерфейсе: разные причины требуют разных
    действий, и по коду ответа это должно быть видно снаружи.
    """

    http_status = 409

    def __init__(self, message: str, *, details: list[str] | None = None):
        super().__init__(message)
        self.message = message
        self.details = details or []
        # Коды регистров учёта, из-за которых отказ. Человеческие названия —
        # дело интерфейса: в расчёте их знать неоткуда и незачем.
        self.ledgers: list[str] = []


class ReasonRequired(PayrunRefused):
    """Переход требует объяснения, а его не написали.

    Свой код ответа, потому что это не «сейчас нельзя» (409), а «в форме не
    хватает поля» (400): исправляется не состоянием периода, а тем, что человек
    допишет причину и нажмёт ещё раз.

    Требование держит триггер базы (`payruns_reason_guard`), и этот класс его не
    заменяет: он превращает отказ в понятный текст **до** записи — тот же
    порядок, что с регистрами учёта. Обязательна ли причина, спрашивается у
    базы (`payrun_reason_required`); своего списка приложение не заводит.
    """

    http_status = 400


class NotReady(PayrunRefused):
    """Месяц не готов к закрытию: есть блокирующие находки (#175).

    409, как и остальные отказы состояния: с запросом всё в порядке, не в
    порядке данные — незакрытые часы, неразобранные бумаги, строки без статьи.
    Отказ называет находки поимённо, чтобы человек знал, что устранять, а не
    искал сам.
    """

    http_status = 409


class LedgerAccessDenied(PayrunRefused):
    """Роль не видит регистры, в которые расчёт собирается писать.

    Это не каприз интерфейса: `insert ... returning` проверяется политиками
    `select`, поэтому запись всё равно упала бы — но ошибкой базы, без
    объяснения.
    """

    http_status = 403
