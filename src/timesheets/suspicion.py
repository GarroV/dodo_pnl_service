"""Подозрительные числа табеля: одно правило на оба пути ввода (T118, T021).

Спека просит подсказку о подозрительном как **must**: часов больше нормы,
сотрудник без часов, отрицательное значение — «чтобы ловить опечатки до
расчёта». Путей ввода при этом два и они равноправны (D011): сетка и загрузка
таблицы партнёра. Проверки жили только во втором, и человек, набиравший руками,
не получал ни одной из них.

**Почему модуль, а не функция рядом с сеткой.** Две копии одной проверки
разъезжаются молча — и разъезжаются именно там, где их никто не сравнивает:
файл сказал бы про человека одно, а сетка про того же человека другое, и
доверия не осталось бы ни к одному. Поэтому текст подсказки собирается здесь
один раз, а импортёр и сетка только раскладывают его по своим местам:
у импортёра к подсказке добавляется лист файла, у сетки — сама строка.

Числа в подсказке форматируются тем же способом, что и вся сетка рядом
(`web.format.hours`): «400.00» посреди столбца из «400,00» читается как число из
другого продукта, а на сербском экране — как число из другого языка.

**Ни одна из подсказок не ошибка сама по себе.** У человека бывает месяц без
часов, норму перерабатывают, а отрицательные часы приходят из файла партнёра как
исправление. Поэтому здесь подсказки, а не отказы: запрет на сохранение отнял бы
у бухгалтера возможность внести то, что есть на самом деле. Ошибкой был бы
**молчаливый** табель, в котором странное видно только тому, кто сложит столбик
руками.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import date
from decimal import Decimal

from django.utils.formats import date_format
from django.utils.translation import gettext as _

from web.format import hours as show_hours

__all__ = ["Hint", "hints"]


@dataclass(frozen=True)
class Hint:
    """Одна подсказка: чем помечена строка и что сказать человеку.

    `kind` — не украшение: по нему экран решает, чем пометить строку, а отчёт
    импорта группирует. Текст на это решение влиять не должен.
    """

    kind: str          # over_norm | no_hours | dismissed | negative
    text: str


def hints(
    *,
    who: str,
    hours: dict,
    norm_hours: Decimal,
    dismissed_at: date | None = None,
    period: date | None = None,
    piecework: bool = False,
) -> list[Hint]:
    """Что в этой строке табеля выглядит подозрительно.

    `who` — как человека называет тот, кто показывает подсказку: подсказка без
    имени в списке из тридцати строк не говорит ничего.

    `piecework` — работа этой группы меряется не часами (D032). Отсутствие часов
    у такой строки не подозрительно вовсе: деньги ей даёт сдельная величина, и
    упрёк «нет ни одного часа» отправил бы человека искать ошибку там, где всё
    правильно. Остальные подсказки остаются: часы у сдельной строки ведут для
    учёта времени, и отрицательные среди них — по-прежнему опечатка.
    """
    found: list[Hint] = []
    total = sum((Decimal(str(value)) for value in hours.values()), Decimal("0"))

    negative = sorted(kind for kind, value in hours.items() if Decimal(str(value)) < 0)
    if negative:
        found.append(Hint(
            "negative",
            _("%(who)s: отрицательные часы (%(kinds)s)")
            % {"who": who, "kinds": ", ".join(negative)},
        ))

    if total == 0:
        if not piecework:
            found.append(Hint(
                "no_hours",
                _("%(who)s: ни одного часа за этот месяц — строка табеля пустая")
                % {"who": who},
            ))
    elif norm_hours > 0 and total > norm_hours:
        found.append(Hint(
            "over_norm",
            _("%(who)s: %(total)s ч при норме %(norm)s ч")
            % {"who": who, "total": show_hours(total), "norm": show_hours(norm_hours)},
        ))

    # Уволен ДО начала месяца — часов у него быть не может. Увольнение в
    # середине месяца ничего не значит: часы до даты увольнения законны.
    if dismissed_at and period and dismissed_at < period and total > 0:
        found.append(Hint(
            "dismissed",
            _("%(who)s: уволен %(date)s, а часов за этот месяц %(total)s")
            % {
                "who": who,
                # Формат языка страницы, а не жёсткий русский (T103).
                # `dismissed_at` — дата без времени (models.py), поэтому берём
                # полный `DATE_FORMAT`, а не машинный `SHORT_DATE_FORMAT`: рядом
                # на той же странице табеля дата закрытия точки показывается
                # полным `DATETIME_FORMAT` (см. grid.html), и эта не должна
                # выглядеть третьим вариантом. `date_format` — не шаблонный
                # фильтр `date`: часовой пояс сам не переводит, но для
                # `DateField` перевода и не нужно — там времени нет.
                "date": date_format(dismissed_at, "DATE_FORMAT"),
                "total": show_hours(total),
            },
        ))
    return found
