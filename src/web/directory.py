"""Правила ведения справочников (T018).

Зачем модуль отдельно от представлений. Экранов пять, а правил, которые они
обязаны соблюдать, — три, и все три общие. Разложенные по пяти представлениям,
они разъедутся на первой же правке, а разъехавшееся правило здесь означает
поехавший закрытый месяц.

**Правило первое: сотрудник заводится вместе с первой версией условий найма
(T164).** Прежде правило было противоположным — справочник сотрудников экранами
не заводился вовсе (D029): карточки приезжали с таблицей партнёра, админка
служила для правки. Для стройки на тестовых данных этого хватало, для передачи
партнёру — нет: человек выходит на работу пятнадцатого числа, и до следующей
загрузки таблицы его в системе не существует.

Отдельной `create_employee` здесь тем не менее не появилось, и это важнее самой
отмены. Заведение — это `Employee.save()` плюс `save_terms` ниже, одной точкой
сохранения (`web/directory_views.employee_new`): второй путь записи условий найма
разъехался бы с первым на первой же правке, а разъехавшееся правило здесь
означает поехавший закрытый месяц. Карточка без условий найма экраном не
заводится — такой человек не попадёт ни в табель, ни в ведомость, и узналось бы
это на расчёте месяца.

**Правило второе: правка версионируемого заводит новую версию, а не переписывает
старую.** Условия найма (`employment_terms`) версионируются по датам, и расчёт
берёт версию, действующую **в считаемом месяце** (`payrun.calc.collect_cases`).
Значит смена ставки — это новая строка с датой начала, а не `update` по месту:
переписанная строка изменила бы прошлое, и июнь, пересчитанный в августе, дал бы
другие числа, чем июнь, посчитанный в июне. Ведомость при этом уже на руках у
людей (D020, T026).

**Правило третье: закрытый месяц не переписывается — но правку задним числом
продукт принимает** (D020, T121). Версия условий найма с датой внутри
утверждённого месяца и изменение нормы часов закрытого месяца проходят, а
закрытый расчёт от них не двигается: сторож базы `payrun_frozen_guard` не даёт
записать в утверждённый расчёт вообще ничего, а разница считается отдельно
(`payrun.retro`) и ложится помеченной строкой в ближайший неутверждённый месяц.

Прежде здесь стоял отказ, и это было расхождение со спекой, а не строгость:
умолчание продукта — перенос разницы, переоткрытие месяца — альтернатива для
партнёра, который настроил иначе (`tenants.retro_mode`). Отказ предлагал
единственной дорогой именно альтернативу, и до умолчания с экрана было не
добраться вовсе.

Молчать об этом тоже нельзя: человек, набравший дату внутри закрытого месяца,
обязан прочитать, что месяц останется прежним и где искать разницу. Слова для
этого — `closed_month_warning` (до правки, на форме) и `closed_month_notice`
(после, на странице-получателе). Текст один на все экраны: три копии одного
объяснения разъедутся на первой же правке.

**Правило пятое: правка общего справочника говорит, что она общая** (T139,
issue #100). Производственный календарь один на страну, и его правка задевает
всех партнёров этой страны. Слова — `shared_calendar_warning` (до правки) и
`shared_calendar_notice` (после), тем же приёмом и в том же месте, что и слова
про закрытый месяц.

**Правило четвёртое: у чего нет версий по датам — то при закрытом месяце не
правится.** Схема расчёта и регистр группы действуют всегда, задним числом их
править нечем: разницу считает пересчёт месяца по версиям, а версии здесь нет.
Отказ остаётся (`refuse_if_unversioned_touches_closed_month`) и советует
выполнимое — переопределить нужное человеку в условиях найма, где дата есть.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import date

from django.db import transaction
from django.utils.translation import gettext as _

from core.models import EmploymentTerm, Payrun
from payrun.calc import month_end
from payrun.retro import DELTA
from payrun.retro import mode as retro_mode

# Поля условий найма, из которых считаются деньги. Правка любого из них — новая
# версия; всё остальное (их сегодня нет) правилось бы по месту. Список нужен
# затем, чтобы «что считается изменением» было записано один раз, а не выведено
# из того, какие поля попали в форму.
VERSIONED_FIELDS = (
    "group_id", "unit_id", "base_rate", "coefficient", "scheme", "ledger",
    # Чем меряется работа этого человека (T164). Деньги считает наравне со
    # схемой: от него зависит, берётся нето из часов или из сдельной величины.
    "work_measure",
)


class DirectoryRefused(Exception):
    """Правка справочника отклонена. Сообщение показывается человеку как есть."""

    # 409, а не 400: с формой всё в порядке, не в порядке состояние данных —
    # месяц закрыт. Разные коды затем, чтобы «вы ошиблись» и «сейчас нельзя»
    # не выглядели одинаково в журнале сервера.
    http_status = 409

    def __init__(self, message: str):
        self.message = message
        super().__init__(message)


def country_of(tenant_id) -> str:
    """Страна партнёра — ключ производственного календаря и пресета правил.

    Читается запросом, а не хранится в `Principal`: тот описан контрактом блока
    `auth`, и дописывать в него поле ради двух экранов значило бы править чужой
    контракт. Выборка идёт под теми же политиками — чужой тенант отсюда не виден.

    Живёт здесь, а не в представлениях, потому что спрашивают её двое: админка
    справочников (календарь) и экран правил (пресет страны). Две копии одного
    запроса разъехались бы ровно в тот день, когда у тенанта появится второй
    источник страны.
    """
    from core.models import Tenant

    return (
        Tenant.objects.filter(pk=tenant_id).values_list("country_code", flat=True).first() or ""
    )


def closed_through(tenant_id) -> date | None:
    """Последний день последнего утверждённого месяца зарплаты. Нет таких — None.

    Почему именно `max`, а не «попадает ли дата в какой-то утверждённый месяц».
    Версия условий найма, начавшая действовать с даты X, влияет на **все** месяцы
    от X и дальше. Значит она не задевает утверждённого, только если начинается
    позже последнего из них. Проверка «попал ли ровно в закрытый месяц»
    пропустила бы правку с датой в открытом мае при утверждённом июне — и июнь
    поехал бы при первом же пересчёте.
    """
    period = (
        Payrun.objects.filter(tenant_id=tenant_id, status="approved")
        .order_by("-period")
        .values_list("period", flat=True)
        .first()
    )
    return month_end(period) if period is not None else None


def refuse_if_unversioned_touches_closed_month(tenant_id, what: str) -> None:
    """Отказать, если правят то, у чего версий по датам нет вовсе.

    Схема расчёта и регистр группы одни на всю историю: они не «начинают
    действовать с даты», они действуют всегда. Значит любая их правка задевает
    и уже утверждённый месяц — не потому, что дату выбрали неудачно, а потому,
    что выбирать нечего.

    Отдельно от слов про перенос разницы (`closed_month_warning`), и это не
    косметика. Пока здесь стоял общий отказ, звали его с `date.min`, и человек получал
    «нельзя изменить с 0001-01-01» и совет «возьмите дату позже»: выдуманную
    дату, которой он не вводил, и действие, которого в этой форме нет — поля
    даты там не бывает. Отказ, советующий невыполнимое, читается как поломка
    продукта, и человек идёт искать несуществующий месяц вместо того, чтобы
    сделать то, что действительно работает.

    Поэтому совет здесь другой и выполнимый: переопределить нужное **человеку**
    в условиях найма — там правка идёт с даты, — либо открыть месяц заново с
    причиной (D021). Оба пути существуют и оба обратимы.
    """
    edge = closed_through(tenant_id)
    if edge is None:
        return
    # Предложение начинается своим словом, а не подставленным (issue #78).
    # Пока текст открывался с `%(what)s`, под плашкой «Не сохранено.» выходило
    # «Не сохранено. схема расчёта и регистр группы нельзя изменить…» — строчная
    # буква сразу за точкой читается как обрезанный текст, то есть как сбой
    # поверх отказа. Заглавная буква у каждого вызывающего означала бы, что
    # `what` придётся склонять и писать по-разному в каждом месте.
    raise DirectoryRefused(
        _(
            "Правку отклонили: %(what)s нельзя изменить, потому что зарплата за "
            "%(month)s уже утверждена, а версий по датам у этой настройки нет — "
            "правка переписала бы закрытый месяц задним числом. Переопределите "
            "нужное человеку в условиях найма: там правка идёт с даты. Либо "
            "откройте месяц заново с причиной."
        )
        % {"what": what, "month": edge.strftime("%Y-%m")}
    )


def touches_closed_month(tenant_id, effective_from: date) -> bool:
    """Задевает ли правка с этой датой уже утверждённую зарплату.

    Не запрет, а признак: от него зависит только то, о чём продукт обязан
    сказать человеку. Сам закрытый месяц защищён не здесь, а базой (сторож
    `payrun_frozen_guard`): проверка в приложении, отвечающая за деньги в
    одиночку, — ровно то, от чего уходит D014.
    """
    edge = closed_through(tenant_id)
    return edge is not None and effective_from <= edge


def closed_month_warning(tenant_id) -> str:
    """Что случится с закрытым месяцем — сказано **до** правки, на форме.

    Пусто, если утверждённых месяцев нет: у нового партнёра предупреждать не о
    чём, а предупреждение «на всякий случай» читается как запрет.

    Слова зависят от того, как партнёр ведёт правки задним числом
    (`tenants.retro_mode`): при переносе разницы и при пересчёте человеку надо
    делать разное, и одна общая фраза отправила бы половину людей не туда.
    """
    edge = closed_through(tenant_id)
    if edge is None:
        return ""
    if retro_mode(tenant_id) == DELTA:
        return _(
            "Зарплата утверждена по %(edge)s включительно. Правку с более ранней "
            "датой продукт примет, но закрытый месяц ею не переписывается: если "
            "она изменит его числа, разница ляжет помеченной строкой в ближайший "
            "неутверждённый месяц — перенести её можно на странице закрытого."
        ) % {"edge": edge.isoformat()}
    return _(
        "Зарплата утверждена по %(edge)s включительно. Правку с более ранней "
        "датой продукт примет, но закрытый месяц ею не переписывается: у этого "
        "партнёра разница применяется пересчётом — откройте месяц заново с "
        "причиной и посчитайте его снова."
    ) % {"edge": edge.isoformat()}


def closed_month_notice(tenant_id) -> str:
    """То же самое **после** правки: что уже случилось и что делать дальше.

    Отдельным текстом, а не тем же самым в будущем времени: «продукт примет»
    после нажатия кнопки читается так, будто ничего ещё не произошло.
    """
    edge = closed_through(tenant_id)
    if edge is None:
        return ""
    if retro_mode(tenant_id) == DELTA:
        return _(
            "Правка задела зарплату, утверждённую по %(edge)s. Закрытый месяц "
            "остался прежним до копейки: если правка изменила его числа, "
            "разница видна на странице этого месяца и переносится оттуда "
            "помеченной строкой в ближайший неутверждённый."
        ) % {"edge": edge.isoformat()}
    return _(
        "Правка задела зарплату, утверждённую по %(edge)s. Закрытый месяц "
        "остался прежним: у этого партнёра разница применяется пересчётом — "
        "откройте месяц заново с причиной и посчитайте его снова."
    ) % {"edge": edge.isoformat()}


def shared_calendar_warning() -> str:
    """Кого заденет правка производственного календаря — сказано **до** неё.

    Календарь общий для страны (`SHARED_TABLES`, `0004_rls`): у него нет
    `tenant_id`, и все партнёры страны читают одну и ту же строку. Пока правка
    закрытого месяца отклонялась, соседей заодно защищал отказ — записи просто
    не возникало. После T121 она проходит (так и требует D020), и расхождение с
    закрытым месяцем появляется у каждого партнёра страны, а не только у того,
    кто правил.

    Сколько именно партнёров — не говорится, и это не лень: тенанты видны
    политикой `own_tenants` только те, где человек состоит, то есть посчитать
    соседей отсюда нечем. Обходить политику ради предупреждения нельзя — это
    ровно тот доступ, который она и закрывает; а число, посчитанное мимо неё,
    рассказало бы человеку о существовании чужих партнёров.

    Не зависит от тенанта намеренно: правило одно на всю страну и на все экраны
    календаря — форма нового месяца и форма правки существующего.
    """
    return _(
        "Календарь общий для страны: правка подействует на всех партнёров этой "
        "страны, а не только на вашего. У тех, у кого этот месяц уже утверждён, "
        "появится своя разница — переносит её каждый у себя."
    )


def shared_calendar_notice() -> str:
    """То же самое **после** правки: кого она уже задела.

    Отдельным текстом, а не тем же в будущем времени, — по той же причине, что у
    `closed_month_notice`: «подействует» после нажатия кнопки читается так, будто
    ничего ещё не произошло.
    """
    return _(
        "Правка календаря подействовала на всех партнёров этой страны, а не "
        "только на вашего: календарь общий. У тех, у кого этот месяц утверждён, "
        "разница появится на странице месяца — переносит её каждый у себя."
    )


@dataclass(frozen=True)
class TermChange:
    """Что именно поменялось между действующей версией и заявленной."""

    changed: bool
    previous: EmploymentTerm | None


def term_at(tenant_id, employee_id, moment: date) -> EmploymentTerm | None:
    """Версия условий найма, действующая на дату. Тем же правилом, что у расчёта."""
    return (
        EmploymentTerm.objects.filter(
            tenant_id=tenant_id, employee_id=employee_id, valid_from__lte=moment
        )
        .exclude(valid_to__lte=moment)
        .order_by("valid_from")
        .last()
    )


def differs(term: EmploymentTerm | None, wanted: dict) -> bool:
    """Отличается ли заявленное от действующей версии хоть одним полем денег."""
    if term is None:
        return True
    for name in VERSIONED_FIELDS:
        if getattr(term, name) != wanted.get(name):
            return True
    return False


@transaction.atomic
def save_terms(tenant_id, employee_id, *, valid_from: date, wanted: dict) -> TermChange:
    """Завести новую версию условий найма с указанной даты.

    Старая версия **закрывается**, а не переписывается: `valid_to` предыдущей
    ставится в день начала новой. Так у человека остаётся история — из неё видно,
    сколько он получал в июне, даже когда в августе у него другая ставка. На этом
    же стоит воспроизводимость закрытого месяца: расчёт июня возьмёт июньскую
    версию, потому что она никуда не делась.

    Ничего не изменилось — не заводим версию вовсе. Иначе история засорялась бы
    строками «то же самое с другой даты», и найти в ней настоящую смену ставки
    стало бы нельзя.
    """
    current = term_at(tenant_id, employee_id, valid_from)
    if not differs(current, wanted):
        return TermChange(changed=False, previous=current)

    # Отказа по закрытому месяцу здесь больше нет (T121): версия с датой внутри
    # утверждённого месяца заводится, а закрытый расчёт остаётся прежним — его
    # держит сторож базы, а не эта функция. Разницу забирает `payrun.retro`.

    if current is not None:
        if current.valid_from == valid_from:
            # Версия начинается тем же днём — она ещё не действовала ни одного
            # дня отдельно от новой, и вторая строка с той же датой всё равно не
            # прошла бы: пересечение периодов запрещено ограничением базы
            # (`employment_terms_no_overlap`). Правим по месту — истории здесь
            # терять нечего.
            for name in VERSIONED_FIELDS:
                setattr(current, name, wanted.get(name))
            current.save(update_fields=list(VERSIONED_FIELDS))
            return TermChange(changed=True, previous=None)
        # Закрываем предыдущую версию днём начала новой. Именно `valid_from`, а
        # не «день до»: границы периодов полуоткрытые (`[valid_from, valid_to)`),
        # и ограничение непересечения в базе написано так же.
        EmploymentTerm.objects.filter(pk=current.pk).update(valid_to=valid_from)

    EmploymentTerm.objects.create(
        tenant_id=tenant_id,
        employee_id=employee_id,
        valid_from=valid_from,
        valid_to=current.valid_to if current is not None else None,
        **wanted,
    )
    return TermChange(changed=True, previous=current)
