"""
Отказы, показанные человеку страницей продукта, а не каркасом (T099).

Что было. На несуществующем адресе человек видел техническую страницу Django:
текст исключения («строка ведомости не найдена»), перечень маршрутов проекта и
настройки — при `DJANGO_DEBUG=1`, а это умолчание, с которым продукт поднимают
локально и показывают коллеге. На площадке (`DJANGO_DEBUG=0`) он видел
стандартное «Not Found» Django — тоже не продукт. Issue #82.

Три требования, из которых собраны эти страницы.

**Страница отказа — такая же страница продукта.** С шапкой, навигацией и
дорогой назад: человек, промахнувшийся адресом, должен уйти отсюда в работу, а
не в браузерную кнопку «назад». Поэтому шаблоны наследуют `web/base.html`, а
текст собран из тех же компонентов, что и остальные экраны.

**Страница отказа ничего не рассказывает.** Это поверхность, на которой легко
проговориться: 404 отвечает одинаково и на несуществующую строку, и на чужую
(так устроены проверки видимости — см. `tests/test_reports_trace.py`), поэтому
она не смеет намекать, что «страница есть, но не ваша». Ни регистров, ни точек,
ни имён, ни адреса, по которому пришли, ни текста исключения — ничего, из чего
можно вычесть существование чужих данных (D023).

**Техническая подробность остаётся разработчику, а не показывается всем.**
Разделение проведено по виду отказа, а не по настройке:

- **404 и 403 — всегда страница продукта**, независимо от `DJANGO_DEBUG`. Это
  обычные положения дел, в которые попадает живой человек: набрал не тот адрес,
  открыл раздел не своей роли. Техническая страница здесь не говорит
  разработчику ничего, чего нет в журнале сервера («Not Found: /path»), а
  человеку показывает лишнее.
- **500 при `DJANGO_DEBUG=1` остаётся трассировкой.** Это не «нормальный
  отказ», а дефект, и трассировка — главный инструмент того, кто его чинит.
  На площадке (`DJANGO_DEBUG=0`) человек видит страницу продукта.

Отказ по правам, который продукт умеет объяснить словами роли
(`permissions.PermissionRefused`), сюда не приходит: его показывают сами
представления своими экранами (`directory/denied.html`, `rules/denied.html`) —
там сказано, какое именно действие не входит в права. Эти страницы — про
случаи, когда объяснить нечего или объяснять нельзя.
"""
from __future__ import annotations

from django.conf import settings
from django.http import HttpResponse
from django.shortcuts import render
from django.utils.html import escape
from django.utils.translation import gettext as _

# Ответ, собранный этим модулем, помечается — чтобы посредник ниже не
# переделывал уже переделанное и не трогал ответы, которые представление
# составило намеренно.
MARK = "is_product_error_page"


def _page(request, template: str, status: int) -> HttpResponse:
    response = render(request, template, status=status)
    setattr(response, MARK, True)
    return response


def page_not_found(request, exception=None) -> HttpResponse:
    """404. Текст исключения сюда не попадает намеренно — он для журнала."""
    return _page(request, "web/errors/404.html", 404)


def permission_denied(request, exception=None) -> HttpResponse:
    """403 без объяснения: сюда приходит то, что объяснить нельзя или нечем."""
    return _page(request, "web/errors/403.html", 403)


def server_error(request) -> HttpResponse:
    """500. С запасным вариантом, потому что падать здесь второй раз нельзя.

    Обычная страница тянет шапку, а шапка ходит в базу за тем, кем вошли. Если
    500 случилась из-за самой базы, соединение может быть в оборванной
    транзакции, и попытка собрать страницу упала бы снова — человек увидел бы
    вместо продукта голое «Server Error (500)» каркаса, то есть ровно то, от
    чего эта задача избавляется. Поэтому запасной вариант — без базы, без
    шапки, только слова.
    """
    try:
        return _page(request, "web/errors/500.html", 500)
    except Exception:  # noqa: BLE001 — здесь важно ответить хоть чем-то
        # Те же слова, что в шаблоне, а не свои: человек не должен читать про
        # одно и то же положение дел два разных текста в зависимости от того,
        # насколько глубоко сломалось.
        title = _("Что-то сломалось на нашей стороне")
        text = _(
            "Мы записали это в журнал. Попробуйте ещё раз через минуту, "
            "а если повторится — скажите тому, кто ведёт сервис."
        )
        language = getattr(request, "LANGUAGE_CODE", "") or "ru"
        response = HttpResponse(
            f'<!doctype html><html lang="{escape(language)}">'
            f'<meta charset="utf-8"><title>{escape(title)}</title>'
            f"<h1>{escape(title)}</h1><p>{escape(text)}</p></html>",
            status=500,
        )
        setattr(response, MARK, True)
        return response


def csrf_failure(request, reason: str = "", template_name: str = "") -> HttpResponse:
    """Форма, отправленная без действительного ключа (штатный CSRF-отказ).

    Своя страница, потому что стандартная у Django техническая и объясняет
    человеку то, чего он не спрашивал. Причина отказа (`reason`) наружу не
    уходит: она из того же теста, что текст исключения, — для журнала.

    Формулировка про устаревшую страницу, а не про «ключ»: у человека это
    обычно и есть устаревшая вкладка или второй вход в соседнем окне.
    """
    return _page(request, "web/errors/403_csrf.html", 403)


class HumanErrorPagesMiddleware:
    """Показать страницу продукта на 404 и при включённой отладке тоже.

    Зачем посредник, если есть `handler404`. Django зовёт его только при
    `DJANGO_DEBUG=0`: с включённой отладкой он подставляет свою техническую
    страницу раньше, и перехватить это представлением нельзя — несуществующий
    адрес не доходит ни до какого представления вовсе (его отвергает
    маршрутизатор). А `DJANGO_DEBUG=1` — умолчание, с которым продукт
    поднимают локально и показывают коллеге, то есть ровно тот случай из
    issue #82.

    Почему только 404. 403 Django отдаёт через `handler403` всегда, независимо
    от отладки, — там посредник не нужен. 500 при включённой отладке обязана
    остаться трассировкой: это дефект, а не положение дел.

    Место в списке посредников не произвольное: **после** `DbContextMiddleware`,
    то есть внутри его транзакции. Страница отказа тянет шапку, шапка спрашивает
    базу, кем вошли, — и спрашивать она должна под тем же контекстом
    пользователя, под которым идёт весь запрос. Снаружи транзакции этот вопрос
    ушёл бы в базу ролью подключения, мимо политик.
    """

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        response = self.get_response(request)
        if not settings.DEBUG or response.status_code != 404:
            return response
        if getattr(response, MARK, False):
            return response
        # Ответ на догрузку куска страницы — не страница: подменять его целым
        # экраном значит вставить шапку внутрь ячейки табеля. Такие ответы
        # продукт составляет сам и намеренно (см. `timesheets/views.py`).
        if request.headers.get("HX-Request"):
            return response
        return page_not_found(request)
