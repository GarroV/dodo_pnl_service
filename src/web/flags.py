"""
Флаги окружения, которые читают и настройки, и код.

Отдельный модуль без единого импорта Django: его читает `config/settings.py`,
то есть он загружается раньше, чем поднимаются приложения. Логика тут же
покрыта тестом — иначе «по умолчанию выключено» проверялось бы глазами.
"""
from __future__ import annotations

# Пароль учёток тестового сида. Не секрет: это данные для разработки, той же
# природы, что пароль базы в .env.example. На площадке сид не гоняется, а
# dev-вход выключен (см. dev_login_enabled).
DEFAULT_DEV_PASSWORD = "dodo-dev"


def dev_login_enabled(env, debug: bool) -> bool:
    """Включён ли вход-ярлык по кнопке вместо ввода пароля.

    Умолчание зависит от `DEBUG`, а не равно «включено»: забыть выставить
    переменную на площадке проще, чем выставить, и цена забывчивости здесь —
    вход в продукт одной кнопкой. Явное значение переменной сильнее умолчания.
    """
    raw = env.get("DEV_LOGIN")
    if raw is None:
        return bool(debug)
    return raw == "1"


def dev_password(env) -> str:
    return env.get("SEED_USER_PASSWORD") or DEFAULT_DEV_PASSWORD
