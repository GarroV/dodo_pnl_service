def role_cards() -> list[dict]:
    """Роли продукта: факты — из формы роли, порядок — из `ROLE_ORDER`.

    `unit` в форме роли — это код точки, которой человек ограничен, или `None`
    («все точки тенанта»). Наружу отдаётся не код, а сам факт ограничения:
    код точки конкретного партнёра на странице, открытой до входа, — это его
    данные, а не устройство продукта.
    """
    cards = []
    for code in ROLE_ORDER:
        shape = ROLE_SHAPES[code]
        cards.append(
            {
                "code": code,
                "title": role_title(code),
                "one_unit": shape.unit is not None,
                # Названия действий, а не коды: код `payslip.freeze` человеку,
                # читающему гайд, не говорит ничего. Порядок — как в форме
                # роли: он там осмысленный (цикл месяца идёт по порядку).
                "actions": [permissions.title(name) for name in shape.permissions],
            }
        )
    return cards


def page(request):
    """«Как это работает». Ни одного запроса к базе — страница открыта до входа."""
    return render(request, "web/guide.html", {"roles": role_cards(), "steps": STEPS})
