@dataclass(frozen=True)
class Step:
    """Один шаг пути партнёра до первой ведомости.

    Четыре поля рядом с названием — требование эталона «Онбординг», и без любого
    из них шаг бесполезен. `why` отвечает на «зачем это вообще»; `route` —
    единственный ответ на «где это в интерфейсе», и он именно маршрут, а не
    написанный руками адрес: переименуют экран — путь соберётся новый сам, а
    выдуманный остался бы вести в никуда. `done` — проверяемый признак, а не
    «настроено»: человек должен уметь сказать «да» или «нет», глядя на экран.
    `trap` — то, на чём спотыкаются, и это не украшение: почти каждый шаг
    ломается одинаково у всех, и дешевле предупредить, чем разбирать потом.
    """

    number: str
    title: object
    where: object
    route: str
    why: object
    done: object
    trap: object


