"""Гайд по продукту внутри самого продукта (T159, T195).

Зачем страница существует. Человек, открывший систему впервые, видит экраны и
не понимает, что это, кем входить и с чего начать. Экраны продукта отвечают на
вопрос «что делать здесь», но ни один из них не отвечает на вопрос «что это
вообще» — и до сих пор ответ жил в документах репозитория, то есть там, где
партнёр его не увидит никогда.

**Ведёт по месяцу, а не описывает экраны (T195, issue #187).** Первая версия
страницы рассказывала про устройство продукта: что такое регистр, кто такие
роли, из чего собирается P&L. Всё верно и всё бесполезно человеку, который сел
и не знает, с чего начать. Эталон «Онбординг» требует другого — путь партнёра
до первой ведомости шагами, и у каждого шага четыре вещи: зачем он нужен, где
он в интерфейсе, готово когда (проверяемый признак, а не «настроено») и где
спотыкаются. Эти шаги лежат ниже в `STEPS`; страница их показывает, а не
пересказывает.

**Открыта до входа, и это требование, а не удобство.** Половина вопроса —
«кем входить»; страница, которую видно только после входа, на него ответить не
может по устройству. Поэтому здесь нет ни одного обращения к базе: гайд говорит
о продукте, а не о данных партнёра, и работать обязан на пустой сессии.

**Роли не переписываются здесь заново.** Форма роли — регистры, точка, права —
берётся из `core.roles.ROLE_SHAPES`, названия ролей из `web.i18n.ROLE_TITLES`,
названия действий из `web.permissions.TITLES`. Ровно потому, что списков ролей в
продукте уже было два и они разъехались молча (issue #91): у администратора сети
набор регистров в продукте и в демо оказался разным, и нашли это по комментарию,
а не по красному тесту. Третьим списком гайд быть не должен — иначе он станет
самым убедительным из неверных: страница, которая объясняет продукт, врёт с
большей силой, чем строка в сиде.

Что здесь всё-таки написано словами — это проза: как роль работает и на какой
экран приходит первой. Она не выводится ни из чего и остаётся текстом, но
привязана к коду роли: появится пятая роль — факты о ней покажутся, а прозы не
будет. Это правильная сторона отказа.

**Регистров учёта страница не перечисляет.** Названия регистров — сообщение о
том, что регистр существует (D023), и непредставившемуся их не показывают: на
том же самом уже спотыкались на форме входа (T096, панель быстрого входа
перечисляла все три регистра и код точки до входа). Механизм объясняется, имена
показывает шапка тому, кто вошёл, и только видимые ему.
"""
