"""Язык интерфейса: выбор, закрепление и то, что нельзя переводить (T017).

Три вещи, которые здесь решены, и почему именно так.

**Русский — язык исходника, а не один из переводов.** Строки в шаблонах и коде
написаны по-русски и служат ключами gettext. Значит непереведённая строка
видна невооружённым глазом: на английской странице она остаётся русской. На
этом и стоит проверка (`tests/test_i18n.py`), а не на «перевод существует».

Исключение одно и оно осознанное: **названия ролей** (`ROLE_TITLES` ниже) идут
через ключи `role.<код>`, а не через русский текст, поэтому у русского языка
появился свой каталог — маленький, только под эти ключи. Почему так, разобрано
у самого словаря. Проверка для них другая, потому что «осталась русской» тут не
работает: непереведённый ключ выглядит как `role.manager`, и его ловит
`test_role_titles_are_translated_in_every_language`.

**Данные не переводятся.** Имена сотрудников, названия точек и партнёров,
подписи компонентов и типов часов из пресета страны — это настройка партнёра,
а не слова продукта. Переводить их значило бы решать за бухгалтера, как
называется его же «Топли оброк». Граница проведена здесь один раз, чтобы её
было где прочитать: словарь ниже переводит только продуктовый словарь —
регистры учёта (в `format.py`) и роли.

**Закрепление языка — ради демо.** Конституция требует, чтобы демо всегда
открывалось по-английски независимо от человека. Это не «язык по умолчанию»
(его перебьёт первый же переключатель), а именно закрепление: с UI_LANGUAGE
переключателя на странице нет вовсе.
"""
from __future__ import annotations

from django.conf import settings
from django.utils import formats, translation
from django.utils.translation import gettext_lazy as _

# Роли продукта. Названия ролей лежат в базе (`roles.title`), но это не данные
# партнёра, а словарь самого продукта: те же роли будут у любого следующего
# партнёра. Поэтому подпись берётся по коду роли, а название из базы остаётся
# запасным вариантом — партнёр вправе завести свою роль, и выдумывать ей
# перевод неоткуда.
#
# Ключ здесь — `role.<код>`, а не русский текст, и это единственное место
# продукта, где так. Причина: названия ролей переименовывают. Пока ключом была
# русская строка, переименование по-русски меняло ключ, и английский с сербским
# ТИХО откатывались на русский текст — без ошибки, без красного теста, просто
# англоязычный человек видел русское слово. Ключ вида `role.manager` от
# переименования не зависит вовсе: меняется значение в каталоге, ключ стоит.
#
# Правило, по которому решать для следующего набора: ключ — терминам из
# закрытого набора, которые существуют как значение в данных и которые владелец
# может переименовать (роли, регистры, статусы периода). Обычной прозе —
# подсказкам, ошибкам, заголовкам — исходная русская строка: её переименовывают
# редко, а `_("Сохранить")` в коде понятно сразу, `_("btn.save")` — нет.
ROLE_TITLES = {
    "director": _("role.director"),
    "accountant": _("role.accountant"),
    "manager": _("role.manager"),
    "admin": _("role.admin"),
    # Роли ещё не заведены в базе, а названия уже решены владельцем на трёх
    # языках. Ключи стоят здесь заранее нарочно: иначе при создании роли
    # сербское название пришлось бы вспоминать, а вспоминают его неверно.
    "regional_manager": _("role.regional_manager"),
    "shift_manager": _("role.shift_manager"),
}


def role_title(code: str, fallback: str = "") -> str:
    """Название роли на языке страницы. Незнакомая роль — как её назвал партнёр."""
    known = ROLE_TITLES.get(code)
    return str(known) if known is not None else fallback


def month_title(value) -> str:
    """«Июнь 2026», «June 2026», «Jun 2026» — месяц на языке страницы.

    Через локали Django, а не своим списком: списки месяцев у трёх языков — это
    тридцать шесть строк, которые никто не станет держать в согласии, при том
    что у Django они уже есть и переведены.

    Первая буква поднимается руками: в сербском и в части языков месяц пишется
    со строчной, а здесь это заголовок строки, а не дата внутри предложения.
    """
    shown = formats.date_format(value, "F Y")
    return shown[:1].upper() + shown[1:]


def forced_language() -> str:
    """Закреплённый язык или пусто. Одно место, где этот вопрос задаётся."""
    code = getattr(settings, "UI_LANGUAGE", "") or ""
    return code if code in dict(settings.LANGUAGES) else ""


class ForcedLanguageMiddleware:
    """Закрепить язык поверх выбора человека, если стенд этого требует.

    Стоит после LocaleMiddleware: тот уже выбрал язык по cookie и заголовку
    браузера, и переопределять его нужно последним словом. Без закрепления
    демо открывалось бы на языке гостя — прямо против правила конституции.

    Ничего не делает, если UI_LANGUAGE пуст или называет язык, которого у нас
    нет: молча включить неизвестный язык — это показать человеку пустой экран
    вместо ошибки.
    """

    def __init__(self, get_response):
        self.get_response = get_response
        self.language = forced_language()

    def __call__(self, request):
        if not self.language:
            return self.get_response(request)
        translation.activate(self.language)
        request.LANGUAGE_CODE = translation.get_language()
        return self.get_response(request)


def switcher(request) -> dict:
    """Контекст-процессор: чем переключать язык в шапке.

    Языки перечисляются из настроек, а не списком в шаблоне: разъехавшиеся
    списки означали бы кнопку без каталога или каталог без кнопки.

    При закреплённом языке список пуст — шапка не рисует переключатель вовсе.
    """
    if forced_language():
        return {"languages": [], "current_language": translation.get_language()}
    current = translation.get_language()
    return {
        "languages": [
            # `short` — то, что видно в шапке: «RU», а не «Русский». Полное
            # название остаётся подсказкой у кнопки. Три полных названия занимали
            # четверть верхней строки и разворачивали шапку на две — то есть
            # ручка, которой пользуются раз в жизни, отодвигала вниз данные,
            # ради которых человек пришёл.
            {
                "code": code,
                "title": title,
                "short": code.split("-")[0].upper(),
                "current": code == current,
            }
            for code, title in settings.LANGUAGES
        ],
        "current_language": current,
    }
