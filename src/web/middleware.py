"""Заголовки, которые продукт ставит на каждый ответ (T161).

Пока стенд жил внутри частной сети, вопрос индексации был теоретическим. С
постоянным публичным адресом он перестал быть теоретическим: страницы с
фамилиями сотрудников и суммами их зарплат не должны попадать в поисковую
выдачу — ни на стенде, ни у партнёра, ни в демо. Индексировать этот продукт
незачем ни в одном развёртывании, поэтому заголовок ставится всегда, а не
переменной окружения: выключатель здесь означал бы, что кто-то однажды забудет
его включить.

Заголовком, а не `robots.txt`: `robots.txt` — просьба к обходчику не заходить,
и её соблюдают не все; `X-Robots-Tag: noindex` — указание не показывать в
выдаче то, что уже скачали.
"""
from __future__ import annotations


class NoIndex:
    """`X-Robots-Tag: noindex, nofollow` на каждый ответ продукта."""

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        response = self.get_response(request)
        response.headers.setdefault("X-Robots-Tag", "noindex, nofollow")
        return response
