"""Словарь разделов продукта — один на всё (issue #162, T194).

Модуль 10 эталона называет области учёта по работе человека, а не по механике
продукта: «Сбор данных», «Расчёт», «Отчёты», «Справочники», «Настройки», а
внутри — «Табель», «Наличные расходы», «Ведомость», «Закрытие месяца». У нас в
шапке стояли «Периоды · Расходы · Счета · Сотрудники»: слова про устройство
базы, а не про то, зачем человек пришёл. Владелец 18.08.2026 сказал ровно об
этом: «я не понимаю, как она работает, где какие функции».

**Зачем отдельный модуль.** Пока названия набраны прямо в шаблоне шапки, они не
сверяются ни с чем: расхождение с эталоном видно только тому, кто помнит обе
картинки целиком. Здесь словарь лежит один раз, а `tests/test_navigation_
dictionary.py` механически сверяет его со словами **из самого эталона** — не из
копии, переписанной в тест.

**Чего здесь нет.** Пунктов, которых в продукте ещё нет: P&L, банковской
выписки, аналитики по людям, выплат. Пункт, ведущий в никуда, хуже
отсутствующего: человек нажимает и упирается в пустой экран, а «пока не
сделано» ему никто не сказал. Они появятся вместе со своими экранами.

**Группы эталона пока не рисуются.** Эталон показывает меню группами со
счётчиками ждущей работы; у нас шапка плоская, и переход к группам — отдельная
работа (T207). Группы здесь заведены сразу, чтобы порядок пунктов был
эталонным уже сейчас, а разметке было куда расти.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from django.utils.translation import gettext_lazy as _

# Названия, которых в словаре эталона нет, и это осознанно. Каждое — с
# причиной: без причины список превращается в способ обойти сверку.
OUR_OWN = {
    # Роли и права: эталон рисует их страницей «Роли и права», а не пунктом
    # навигации (в его меню стоят «Доступы» — то же самое другими словами).
    # Наше имя оставлено, потому что оно совпадает с названием экрана, на
    # который ведёт, и с языком решений (D033, D052).
    "Роли и права",
}


@dataclass(frozen=True)
class Item:
    """Пункт навигации: имя из словаря, адрес и право, без которого его не видно."""

    title: object          # `gettext_lazy`, поэтому не `str`
    route: str             # имя маршрута Django
    needs: str = ""        # право; пусто — виден всем вошедшим
    without: str = ""      # виден только тому, у кого этого права НЕТ


@dataclass(frozen=True)
class Group:
    """Область учёта эталона: «Сбор данных», «Расчёт», «Справочники»…"""

    title: object
    items: list = field(default_factory=list)


# Порядок групп и пунктов — эталонный. Он же порядок в плоской шапке: человек,
# читавший макет, найдёт разделы там, где привык.
GROUPS = [
    Group(_("Сбор данных"), [
        # «Табель» вместо «Периоды»: человек приходит вносить часы, а не
        # открывать учётный месяц. Адрес прежний — список периодов, потому что
        # табель живёт внутри месяца.
        Item(_("Табель"), "periods"),
        Item(_("Наличные расходы"), "expenses"),
        # Ведёт в ИНБОКС, а не в список счетов: эталон называет этим пунктом
        # очередь того, что ждёт разбора, — с неё и начинается работа с
        # первичкой. Список счетов открывается из инбокса ссылкой и живёт в том
        # же разделе (`NAV_BELONGS` в `templatetags/ui.py`).
        Item(_("Инбокс документов"), "inbox"),
    ]),
    Group(_("Справочники"), [
        # Сотрудники стоят пунктом только у того, у кого нет раздела
        # справочников: у администратора он ведёт туда же, и два входа в один
        # экран из одной шапки читались бы как два разных места (T173).
        Item(_("Сотрудники"), "directory-employees", without="directory.manage"),
        Item(_("Справочники"), "directory", needs="directory.manage"),
        Item(_("Правила расчёта"), "rules", needs="rules.manage"),
    ]),
    Group(_("Настройки"), [
        Item(_("Роли и права"), "roles", needs="roles.manage"),
    ]),
]


def visible_for(principal) -> list:
    """Пункты, которые видит этот человек. Порядок — эталонный.

    Право проверяется здесь, а не в шаблоне, по той же причине, по которой
    словарь лежит в модуле: правило видимости, размазанное по разметке, нельзя
    ни прочитать целиком, ни проверить. Срез ДАННЫХ при этом по-прежнему делает
    база (D014) — здесь решается только то, показывать ли ссылку.
    """
    from . import permissions

    shown = []
    for group in GROUPS:
        for item in group.items:
            if item.needs and not permissions.has(principal, item.needs):
                continue
            if item.without and permissions.has(principal, item.without):
                continue
            shown.append(item)
    return shown


def sections(request) -> dict:
    """Разделы шапки для шаблона — контекст-процессором, а не в каждой вьюхе.

    Шапка стоит на всех страницах, и собирать её в тридцати представлениях
    значило бы тридцать мест, где о новом разделе можно забыть.
    """
    from django.urls import reverse

    from . import permissions
    from .principal import get_current_principal

    who = get_current_principal(request)
    rows = []
    for group in GROUPS:
        for item in group.items:
            allowed = (
                (not item.needs or permissions.has(who, item.needs))
                and (not item.without or not permissions.has(who, item.without))
            )
            rows.append({
                "title": item.title,
                "url": reverse(item.route),
                "needs": item.needs,
                "route": item.route,
                "allowed": allowed,
                # Предложение переключить роль показывается только в демо и
                # только у раздела, который ведёт КОНКРЕТНОЕ право: у пункта без
                # права предлагать нечего (T163).
                "offer": bool(item.needs) and not allowed,
            })
    return {"nav_sections": rows}

