"""Словарь разделов продукта — один на всё (issue #162, T194).

Модуль 10 эталона называет области учёта по работе человека, а не по механике
продукта: «Сбор данных», «Расчёт», «Отчёты», «Справочники», «Настройки», а
внутри — «Табель», «Наличные расходы», «Ведомость», «Закрытие месяца». У нас в
шапке стояли «Периоды · Расходы · Счета · Сотрудники»: слова про устройство
базы, а не про то, зачем человек пришёл. Владелец 18.08.2026 сказал ровно об
этом: «я не понимаю, как она работает, где какие функции».

**Зачем отдельный модуль.** Пока названия набраны прямо в шаблоне шапки, они не
сверяются ни с чем: расхождение с эталоном видно только тому, кто помнит обе
картинки целиком. Здесь словарь лежит один раз, а `tests/test_navigation_
dictionary.py` механически сверяет его со словами **из самого эталона** — не из
копии, переписанной в тест.

**Чего здесь нет.** Пунктов, которых в продукте ещё нет: P&L, банковской
выписки, аналитики по людям, выплат. Пункт, ведущий в никуда, хуже
отсутствующего: человек нажимает и упирается в пустой экран, а «пока не
сделано» ему никто не сказал. Они появятся вместе со своими экранами.

**Группы рисуются меню, а счётчик показывает ждущую работу** (T207). Область
учёта — раскрывающееся меню в шапке, внутри — её пункты; у пункта стоит число
работы, которая ждёт человека, у области — сумма по её пунктам. Ноль не
показывается вовсе: это дословное правило эталона («Счётчик у пункта — это
работа, которая ждёт человека. Ноль не показываем»), и оно не про экономию
места — ноль сообщает «здесь есть очередь, и она пуста», а показывать надо
обратное.

**Счётчик берётся из того же места, что и сам экран.** Не «похожим запросом», а
вызовом той же функции: два ответа на один вопрос расходятся молча — например,
когда политики базы сузят один не так, как другой, и человек увидит в шапке
чужое число. Поэтому у пункта не «сколько-то там», а вызов источника его
собственного списка (`waiting=` у `Item`).
"""
from __future__ import annotations

from dataclasses import dataclass, field

from django.utils.translation import gettext_lazy as _

# Названия, которых в словаре эталона нет, и это осознанно. Каждое — с
# причиной: без причины список превращается в способ обойти сверку.
OUR_OWN = {
    # Роли и права: эталон рисует их страницей «Роли и права», а не пунктом
    # навигации (в его меню стоят «Доступы» — то же самое другими словами).
    # Наше имя оставлено, потому что оно совпадает с названием экрана, на
    # который ведёт, и с языком решений (D033, D052).
    "Роли и права",
}


def inbox_waiting(who) -> int:
    """Сколько работы ждёт в инбоксе — теми же выборками, что и его экран.

    Списка на экране два, и оба ждут одного человека: строки без статьи и
    бумаги, принесённые с точек (T174). Считать только первый значило бы
    показывать в шапке меньше, чем человек увидит, открыв раздел.

    Зовём **источники** обоих списков, а не пишем свой запрос: свой сузился бы
    иначе — например, мимо политик, которые режут строки по точке и регистру, —
    и число в шапке молча разошлось бы со списком. Считать по готовым строкам,
    а не `count()` по базе, здесь дешевле правильного: инбокс — очередь, которую
    человек разбирает руками, и длина у неё человеческая.
    """
    from . import papers, suppliers

    return (
        len(suppliers.waiting_for_an_article(who))
        + len(papers.papers(who, only_waiting=True))
    )


@dataclass(frozen=True)
class Item:
    """Пункт навигации: имя из словаря, адрес и право, без которого его не видно."""

    title: object          # `gettext_lazy`, поэтому не `str`
    route: str             # имя маршрута Django
    needs: str = ""        # право; пусто — виден всем вошедшим
    without: str = ""      # виден только тому, у кого этого права НЕТ
    # Чем считается ждущая работа: функция от человека, возвращающая число.
    # None — у пункта очереди нет, и счётчику взяться неоткуда.
    waiting: object = None


@dataclass(frozen=True)
class Group:
    """Область учёта эталона: «Сбор данных», «Расчёт», «Справочники»…"""

    title: object
    items: list = field(default_factory=list)


# Порядок групп и пунктов — эталонный. Он же порядок в плоской шапке: человек,
# читавший макет, найдёт разделы там, где привык.
GROUPS = [
    Group(_("Сбор данных"), [
        # «Табель» вместо «Периоды»: человек приходит вносить часы, а не
        # открывать учётный месяц. Адрес прежний — список периодов, потому что
        # табель живёт внутри месяца.
        Item(_("Табель"), "periods"),
        Item(_("Наличные расходы"), "expenses"),
        # Ведёт в ИНБОКС, а не в список счетов: эталон называет этим пунктом
        # очередь того, что ждёт разбора, — с неё и начинается работа с
        # первичкой. Список счетов открывается из инбокса ссылкой и живёт в том
        # же разделе (`NAV_BELONGS` в `templatetags/ui.py`).
        Item(_("Инбокс документов"), "inbox", waiting=inbox_waiting),
    ]),
    Group(_("Справочники"), [
        # Сотрудники стоят пунктом только у того, у кого нет раздела
        # справочников: у администратора он ведёт туда же, и два входа в один
        # экран из одной шапки читались бы как два разных места (T173).
        Item(_("Сотрудники"), "directory-employees", without="directory.manage"),
        Item(_("Справочники"), "directory", needs="directory.manage"),
        Item(_("Правила расчёта"), "rules", needs="rules.manage"),
    ]),
    Group(_("Настройки"), [
        Item(_("Роли и права"), "roles", needs="roles.manage"),
    ]),
]


def visible_for(principal) -> list:
    """Пункты, которые видит этот человек. Порядок — эталонный.

    Право проверяется здесь, а не в шаблоне, по той же причине, по которой
    словарь лежит в модуле: правило видимости, размазанное по разметке, нельзя
    ни прочитать целиком, ни проверить. Срез ДАННЫХ при этом по-прежнему делает
    база (D014) — здесь решается только то, показывать ли ссылку.
    """
    from . import permissions

    shown = []
    for group in GROUPS:
        for item in group.items:
            if item.needs and not permissions.has(principal, item.needs):
                continue
            if item.without and permissions.has(principal, item.without):
                continue
            shown.append(item)
    return shown


def sections(request) -> dict:
    """Области учёта для шапки — контекст-процессором, а не в каждой вьюхе.

    Шапка стоит на всех страницах, и собирать её в тридцати представлениях
    значило бы тридцать мест, где о новом разделе можно забыть.

    Что здесь решается и почему именно здесь:

    * **какие пункты человек ведёт** — правом, а не разметкой (см. `visible_for`);
    * **в какой области он сейчас** — тем же фильтром `in_section`, которым
      выделяется сам пункт. Второе правило «где человек» разъехалось бы с первым
      на первом же вложенном экране;
    * **сколько работы ждёт** — вызовом источника списка (`Item.waiting`), и
      только у пункта, который человек действительно ведёт: считать чужую
      очередь и не показывать её означало бы платить запросом за ничто;
    * **показывать ли область целиком.** Область, где нет ни одного своего
      пункта, в продукте не рисуется вовсе: открыть меню и увидеть пустоту хуже,
      чем не увидеть кнопку. В демо она остаётся — там внутри стоит предложение
      открыть раздел подходящей ролью (T163), и без области оно было бы негде.
    """
    from django.conf import settings
    from django.urls import reverse

    from . import permissions
    from .principal import get_current_principal
    from .templatetags.ui import in_section

    who = get_current_principal(request)
    # Считать очередь есть смысл только у вошедшего: до входа шапка разделов не
    # показывает вовсе, а запрос в базу без контекста партнёра ничего не значит.
    counting = who is not None and who.tenant_id is not None

    areas = []
    for group in GROUPS:
        items = []
        for item in group.items:
            allowed = (
                (not item.needs or permissions.has(who, item.needs))
                and (not item.without or not permissions.has(who, item.without))
            )
            url = reverse(item.route)
            items.append({
                "title": item.title,
                "url": url,
                "needs": item.needs,
                "route": item.route,
                "allowed": allowed,
                # Предложение переключить роль показывается только в демо и
                # только у раздела, который ведёт КОНКРЕТНОЕ право: у пункта без
                # права предлагать нечего (T163).
                "offer": bool(item.needs) and not allowed,
                "here": allowed and in_section(request.path, url),
                "waiting": (
                    item.waiting(who)
                    if allowed and counting and item.waiting is not None
                    else 0
                ),
            })

        mine = [item for item in items if item["allowed"]]
        offers = [item for item in items if item["offer"]]
        if not mine and not (getattr(settings, "DEMO_MODE", False) and offers):
            continue

        areas.append({
            "title": group.title,
            "items": items,
            "here": any(item["here"] for item in items),
            "waiting": sum(item["waiting"] for item in items),
            # Чем заменить область, у которой человек не ведёт ни одного пункта:
            # в демо это ссылка «открыть ролью, которая её ведёт». Право и адрес
            # берутся у первого её пункта — предлагать сразу три способа войти в
            # одну область значило бы спрашивать посетителя о том, чего он ещё
            # не знает.
            "offer": None if mine else {
                "needs": offers[0]["needs"], "route": offers[0]["route"],
            },
        })
    return {"nav_areas": areas}

