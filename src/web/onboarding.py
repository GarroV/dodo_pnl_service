"""Что делать дальше: порядок работы за месяц и пустые состояния (T077).

Замечание владельца после первого живого просмотра продукта: «очень интересно,
но онбординг явно нужен». Он прав ровно в том, что интерфейс был написан для
того, кто его строил: экраны честно показывают данные и честно объясняют
запреты, но нигде не сказано, **с чего месяц начинается**.

Поэтому здесь одна вещь — три шага месяца и то, на каком из них человек сейчас.
Считается она по фактам о данных (есть ли часы, был ли расчёт, утверждён ли
период), а не по разметке: шаг — это состояние периода, и вычислять его в
шаблоне значило бы завести второй источник истины о том же самом.

Текущий шаг ровно один. Полоса отвечает на вопрос «что делать сейчас», а не
«что бывает вообще»: два выделенных шага — это опять выбор, которого человек,
впервые открывший продукт, сделать не может.
"""
from __future__ import annotations

from django.utils.translation import gettext_lazy as _

# Три шага месяца. Порядок жёсткий и он же порядок работы: без часов нечего
# считать, без расчёта нечего утверждать. Подписи — не украшение: рядом с
# названием шага стоит то, что человек должен сделать, а не то, как шаг
# называется по-научному.
STEPS = (
    {
        "code": "hours",
        "name": _("1. Часы"),
        "hint": _("Внесите отработанные часы в табеле или загрузите их таблицей."),
    },
    {
        "code": "calculate",
        "name": _("2. Расчёт"),
        "hint": _("Посчитайте период — получится ведомость по видимым вам регистрам."),
    },
    {
        "code": "approve",
        "name": _("3. Утверждение"),
        "hint": _("Утвердите период: расчёт замораживается, откат — только с причиной."),
    },
)


def month_steps(
    *, has_hours: bool | None = None, calculated: bool = False, approved: bool = False
) -> list[dict]:
    """Полоса шагов месяца. Без `has_hours` — просто порядок работы, без «сейчас».

    Так она и стоит на списке периодов: какой месяц и на каком он шаге, оттуда
    не видно, и выделять шаг наугад значило бы врать человеку в первом же, что
    он читает.
    """
    if has_hours is None:
        return [{**step, "done": False, "now": False} for step in STEPS]

    done = {
        "hours": has_hours,
        "calculate": calculated,
        "approve": approved,
    }
    # Текущий — первый невыполненный. Все выполнены — текущего нет: месяц
    # закончен, и подсказывать больше нечего.
    current = next((step["code"] for step in STEPS if not done[step["code"]]), "")
    return [
        {**step, "done": done[step["code"]], "now": step["code"] == current}
        for step in STEPS
    ]
