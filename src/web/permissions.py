"""Права роли: одно место, где действие сверяется с ролью (T064).

Зачем модуль, если права уже проверяет база. Ограничивающие политики (миграция
`0022_role_permissions`) — это гарантия: роль без права не запишет строку, даже
если новый экран забудет спросить. Но отвечает база кодом ошибки, из которого
человеку ничего не понятно, а на экране «нельзя» должно быть сказано словами —
так же, как уже сделано для регистров учёта.

Поэтому здесь только формулировки и одна проверка, а не второй движок доступа:
что человек может, решает роль, применяет база, объясняет этот модуль.

Права **не подразумеваются друг из друга**: «умею считать период» не значит
«умею править табель». Иерархия ролей появилась бы вторым источником истины
рядом с самим списком прав.
"""
from __future__ import annotations

from django.utils.translation import gettext as _
from django.utils.translation import gettext_noop

# Коды прав. Ровно те, что стоят в политиках базы: разъехавшиеся списки означали
# бы, что интерфейс обещает не то, что позволяет база.
TIMESHEET_EDIT = "timesheet.edit"
PAYRUN_CALCULATE = "payrun.calculate"
# Утверждение и откат — два разных права, а не одно «управление периодом»
# (T025). Бухгалтер в сиде утверждает, но не открывает: открытие закрытого
# месяца — решение другого веса, и объединять их значило бы выдать второе
# вместе с первым.
PERIOD_APPROVE = "period.approve"
PERIOD_REOPEN = "period.reopen"
UNIT_CLOSE = "unit.close"
# Заморозка спорной строки ведомости (T027). Отдельное право, а не следствие
# «умею утверждать»: отказ показывает название действия, и человек, нажавший
# «Заморозить строку», прочитал бы «Утверждение периода не входит в права
# вашей роли» — один запрет чужими словами.
PAYSLIP_FREEZE = "payslip.freeze"
# Перенос разницы из закрытого месяца в текущий (T026). Тоже отдельное, и по
# тому же доводу: на «Перенести разницу» человек прочитал бы «Расчёт периода не
# входит в права вашей роли» — один запрет чужими словами.
RETRO_POST = "retro.post"

# Что показать человеку. Отказ называет само действие, а не код права: «нет
# payrun.calculate» — сообщение для разработчика, а не для бухгалтера.
#
# Название действия переводится на язык страницы (T017): отказ читает человек, и
# читает он его на том же языке, на котором написана кнопка, которой нет.
#
# В словаре `gettext_noop`, а перевод — в `title()`. Так, а не `gettext_lazy`,
# потому что значение уходит не только на страницу: оно попадает в поле `error`
# фоновой задачи и в текст исключения, а отложенный объект там либо падает при
# сериализации, либо превращается в служебный мусор. Пометка при этом
# обязательна: без неё `makemessages` эти семь строк не увидит вовсе.
#
# И вызывается она **своим полным именем**, а не через короткий псевдоним.
# Извлечение строк смотрит на имя функции в тексте файла, а не на то, что она
# на самом деле делает: `noop("…")` для него — обычный вызов, и строка молча не
# попадает в каталог. Найдено в браузере: сообщение об отказе выводилось
# наполовину переведённым — «Расчёт периода is outside the permissions of your
# role». Каталог при этом был зелёным: сравнивать было не с чем.
TITLES = {
    TIMESHEET_EDIT: gettext_noop("Правка табеля"),
    PAYRUN_CALCULATE: gettext_noop("Расчёт периода"),
    PERIOD_APPROVE: gettext_noop("Утверждение периода"),
    PERIOD_REOPEN: gettext_noop("Откат периода"),
    UNIT_CLOSE: gettext_noop("Закрытие часов по точке"),
    PAYSLIP_FREEZE: gettext_noop("Заморозка строки ведомости"),
    RETRO_POST: gettext_noop("Перенос разницы за закрытый месяц"),
}


def title(code: str) -> str:
    """Название действия на языке страницы. Незнакомый код — как есть."""
    known = TITLES.get(code)
    return _(known) if known is not None else code


def message(code: str, role_title: str = "") -> str:
    """Почему нельзя — одними и теми же словами до действия и после.

    Страница спрашивает это, чтобы объяснить, почему кнопки нет; отказ на само
    действие — чтобы объяснить 403. Две формулировки одного запрета разъехались
    бы на первой правке, и человек читал бы про один и тот же запрет разное.

    Форм две, а не одна со вставкой (T017): в языке, где роль стоит в другом
    падеже или в другом месте предложения, «хвост» из кавычек переводчику не
    приставить. Пустая роль — не редкость: до входа роли нет вовсе.
    """
    action = title(code)
    if role_title:
        return _(
            "%(action)s не входит в права вашей роли «%(role)s». "
            "Попросите того, у кого это право есть."
        ) % {"action": action, "role": role_title}
    return _(
        "%(action)s не входит в права вашей роли. "
        "Попросите того, у кого это право есть."
    ) % {"action": action}


class PermissionRefused(Exception):
    """Действие не входит в права роли. Сообщение показывается как есть."""

    http_status = 403

    def __init__(self, code: str, role_title: str = ""):
        self.code = code
        self.role_title = role_title
        self.message = message(code, role_title)
        super().__init__(self.message)


def check(who, code: str) -> None:
    """Пропустить, если право есть. Иначе — отказ с внятным текстом.

    `who is None` — тоже отказ: без вошедшего пользователя прав нет ни одного.
    Умолчание именно такое, потому что обратное («не знаем — разрешаем») здесь
    ошибается ровно в ту сторону, в которую ошибаться нельзя.
    """
    if who is None or code not in (who.permissions or []):
        raise PermissionRefused(code, getattr(who, "role_title", ""))


def has(who, code: str) -> bool:
    """То же самое вопросом — для страниц, которые решают, что показывать."""
    return who is not None and code in (who.permissions or [])


def explain(who, code: str) -> str:
    """Пусто, если право есть; иначе текст, объясняющий отсутствие действия.

    Страница обязана и не предлагать невозможного, и не молчать об этом:
    исчезнувшая без объяснения кнопка читается как поломка продукта, а не как
    запрет. Поэтому одна функция отвечает сразу на оба вопроса — «показывать
    ли» и «что написать вместо».
    """
    if has(who, code):
        return ""
    return message(code, getattr(who, "role_title", ""))
