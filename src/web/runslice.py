"""Что из состояния расчёта показывать смотрящему (T114).

**Зачем модуль.** Расчёт периода идёт по всему партнёру: и по точкам, которых
человек не видит, и по регистрам учёта, которых ему не отдают. Пока всё едет
выборками из таблиц, срез делает база — забытый фильтр даёт пустой результат, а
не утечку (D014). Но задание расчёта (`payrun_jobs`) хранит **свой** рассказ о
том же самом: текст отказа, список тех, у кого не сошлось, и счётчик
посчитанных. Этот рассказ собран по всему периоду и в политики не заходит
вовсе — он приезжает готовой строкой в поле. Значит, срез ему нужен свой, и он
здесь.

**Правило, по которому режем.** Подробности отказа и счётчик расчёта
показываются тому, кому база отдаёт **весь** расчёт партнёра: все регистры
учёта и все точки. Это ровно тот довод, по которому уже решено, кто вправе
морозить строку (T101, `payrun.freezing.rows_are_freezable`): пока ответ зависит
от содержимого строки, само разрешение начинает называть людей — «эту показываю,
эту нет» и есть поимённый список тех, у кого есть выплаты в скрытом регистре.
Здесь то же самое: список, отфильтрованный под смотрящего, менялся бы вместе со
скрытыми данными, а показанный «сколько осталось» — пересчитывал бы их.

**Что смотрящему остаётся.** Отказ обязан быть полезен и тому, кому подробности
не отданы: он говорит, что расчёт не выполнен и почему — причина названа
классом данных («нет схем расчёта», «база для взносов не сходится с часами»), а
не людьми. Людей в тексте отказа не пересчитывают вовсе: число «35 чел.» — тот
же счётчик скрытых строк, только словами, поэтому его нет и у тех, кому весь
расчёт отдан (см. `payrun.calc`). Вместо исчезнувшего списка стоит объяснение,
почему его нет, — молчание читалось бы как поломка продукта, а не как запрет
(тот же порядок, что у кнопок: `web.permissions.explain`).

**Почему объяснение показывается всегда, а не когда есть что прятать.** Оно
свойство роли, а не данных. Появляясь только при непустом списке, оно само
рассказывало бы о существовании скрытых имён — то есть было бы той же утечкой
на один бит.
"""
from __future__ import annotations

from uuid import UUID

from django.db import connection
from django.utils.translation import gettext as _
from django.utils.translation import gettext_noop

__all__ = ["DETAILS_WITHHELD", "details_note", "sees_whole_run", "state_for_viewer"]

DETAILS_WITHHELD = gettext_noop(
    "Кто именно не прошёл проверку, видно тому, кому отдан весь расчёт "
    "партнёра, — спросите бухгалтера или оперативного директора."
)


def sees_whole_run(tenant_id: UUID) -> bool:
    """Отдан ли этой роли весь расчёт партнёра: все регистры и все точки.

    Спрашивается у базы, а не разбирается в Python, — и спрашиваются **те самые
    функции, на которых стоят политики** (`app_sees_every_ledger` из миграции
    `0023`, `app_unit_ids` из `0011`). Вторая правда о видимости рядом с первой
    однажды разойдётся с ней молча (D014), и разойдётся именно здесь: набор
    регистров роли и список её точек меняются экраном ролей.

    Обе половины обязательны, и каждая ловит свою утечку: без первой отказ
    называет людей скрытого регистра (внутренние курьеры), без второй — людей
    чужой точки (BG1 управляющему NS1).
    """
    with connection.cursor() as cursor:
        cursor.execute(
            "select app_sees_every_ledger(%s) and app_unit_ids(%s) is null",
            [tenant_id, tenant_id],
        )
        return bool(cursor.fetchone()[0])


def details_note(*, whole_run: bool) -> str:
    """Пусто, если подробности отданы; иначе текст вместо них."""
    return "" if whole_run else _(DETAILS_WITHHELD)


def state_for_viewer(state: dict, *, whole_run: bool) -> dict:
    """Состояние расчёта, пригодное к показу этому смотрящему.

    Убирается ровно то, что рассказывает о данных всего партнёра:

    * `details` — имена и сквозные ключи (`external_id`, на боевых данных ЈМБГ);
    * `done` и `total` — сколько человек в расчёте. Управляющему точки писалось
      `total: 35` при семнадцати в его собственном табеле.

    `percent` остаётся: доля — не число людей, и полоса прогресса без неё
    перестала бы работать у всех, кроме директора. `stage`, `status` и `hint`
    остаются по той же причине: они говорят о ходе работы, а не о том, чьи это
    строки.

    Новое значение — новый словарь, старый не трогаем: `state_of` зовут и
    страница, и опрос, и молчаливая правка на месте однажды доехала бы не туда.
    """
    if whole_run:
        return state
    return {**state, "details": [], "done": 0, "total": 0}
