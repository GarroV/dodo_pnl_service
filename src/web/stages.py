_PLANNED_BY_ROUTE = {f"planned-{item.code}": item for item in PLANNED_SCREENS}


def planned_screens() -> list:
    """Ненаписанные экраны — для маршрутов и для навигации."""
    return list(PLANNED_SCREENS)


def for_route(name: str) -> Stage | None:
    """Состояние экрана по имени маршрута. `None` — экран готов.

    Спрашивают отсюда и шапка, и сам экран: один источник вместо двух списков,
    которые разъехались бы молча.
    """
    if not name:
        return None
    if name in REFINED:
        return Stage(REFINING, REFINED[name])
    if name in _PLANNED_BY_ROUTE:
        # Не `planned.what`: подробное описание стоит в теле самой заглушки, и
        # в плашке оно повторилось бы слово в слово — поймано на первом же
        # снимке экрана. Плашка говорит состояние, страница — содержание.
        return Stage(PLANNED, _("Экрана ещё нет — ниже то, что здесь появится"))
    return None


def current(request) -> dict:
    """Состояние текущего экрана — контекст-процессором, для плашки в каркасе.

    В каркасе, а не в каждом шаблоне: экранов сорок девять, и пометка, которую
    надо не забыть дописать руками, однажды не будет дописана — причём заметит
    это не разработчик, а тот, кому показывают продукт.

    Имя маршрута берётся из резолвера, потому что состояние — свойство экрана, а
    не адреса: у табеля и закрытия месяца общий корень `/periods/`.
    """
    match = getattr(request, "resolver_match", None)
    return {"screen_stage": for_route(getattr(match, "url_name", "") if match else "")}
