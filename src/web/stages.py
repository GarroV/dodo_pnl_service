"""Состояние экрана: готов, дорабатывается или ещё не написан (D066).

Владелец 31.08.2026, открыв демо: «в демо нужны вообще все экраны , те что
сейчас в дработке - так и помечаем что В ДОРАБОТКЕ», и следом, уточняя
формулировки: «там где что-т оесть и мы дорабатываем - там доработка. там где
ничего нет - разработка в процессе».

**Что этим отменяется.** Прежнее правило навигации было обратным: пунктов,
которых в продукте нет, в шапке не рисовали — «пункт, ведущий в никуда, хуже
отсутствующего: человек нажимает и упирается в пустой экран, а „пока не
сделано“ ему никто не сказал». Довод верный ровно наполовину: он про экран,
который молчит. Помеченный экран не молчит — он называет своё состояние, и
тогда пункт перестаёт вести в никуда.

Цена прежнего правила выяснилась на показе. Владелец открыл демо и решил, что
половины продукта нет, — при том что P&L, сверка и выгрузки были построены и
отвечали `200`. Они просто не попали в шапку (#218). То есть скрывать неполноту
дороже, чем признавать: **скрытый экран читается как отсутствующий, помеченный —
как запланированный.**

**Почему состояния два, а не одно.** «Дорабатываем начатое» и «ещё не
начинали» — разные обещания смотрящему, и слить их в одно значило бы соврать
в одну из двух сторон. Слово «беднее», которым состояние называлось в
`docs/product-map.md`, из лексикона убрано тем же решением.

**Почему словарь здесь, а не в разметке.** Пометка нужна в двух местах сразу —
в шапке рядом с пунктом и плашкой на самом экране, — и два списка разъехались
бы молча: в меню «доработка», внутри пусто. Здесь список один, и оба места
спрашивают его.

Ключ — **имя маршрута**, а не адрес. У табеля и закрытия месяца общий корень
`/periods/`, но состояния разные: табель готов, закрытие дорабатывается (#215).
По адресу их не различить, по имени маршрута — да.
"""
from __future__ import annotations

from dataclasses import dataclass

from django.utils.translation import gettext_lazy as _

__all__ = [
    "PLANNED",
    "REFINING",
    "Stage",
    "current",
    "for_route",
    "planned_screens",
]

# Экран есть и работает, но до нарисованного не дотягивает.
REFINING = "refining"

# Экрана нет вовсе: стоит заглушка, которая честно говорит, что здесь будет.
PLANNED = "planned"


# Как состояние называется человеку. Слова владельца, дословно (D066): «там где
# что-т оесть и мы дорабатываем - там доработка. там где ничего нет - разработка
# в процессе».
LABELS = {
    REFINING: _("Доработка"),
    PLANNED: _("Разработка в процессе"),
}


@dataclass(frozen=True)
class Stage:
    """Состояние экрана и одна фраза о том, чего в нём не хватает."""

    kind: str
    # Что именно дорабатываем (REFINING) или что здесь появится (PLANNED).
    # Общей фразы «в доработке» мало: она не отличает экран, которому не хватает
    # одной кнопки, от экрана, где нет половины замысла.
    note: object

    @property
    def label(self):
        return LABELS[self.kind]


@dataclass(frozen=True)
class Planned:
    """Ненаписанный экран: заголовок, зачем он и когда его очередь."""

    code: str
    # Адрес — здесь, рядом с самим экраном, а не в `urls.py`: маршруты для этих
    # страниц собираются циклом по этому списку, и заводить экран в двух местах
    # значило бы однажды завести его в одном.
    url: str
    title: object
    what: object
    # Место в продуктовой карте — чтобы смотрящий видел не «когда-нибудь», а
    # очередь. Без неё «в разработке» читается как «может, никогда».
    when: object


