"""Экран ролей говорит, кого в списке нет и почему (T160).

Почему здесь нет проверок на пустое состояние — и почему это не пропуск.

Задача T160 требует, чтобы каждый пустой список объяснял себя. На экране ролей
пустого списка не бывает **по устройству**: он открывается по праву
`roles.manage`, а право приходит членством с ролью (`web.permissions.check` в
`roles_views.index`). Значит у того, кто смотрит на экран, уже есть и роль, и
членство — обе таблицы при нём непусты всегда. Первая версия этой работы
добавляла им пустые состояния, и они прошли тест только потому, что тест рисовал
шаблон с выдуманным пустым контекстом, минуя представление: три недостижимых
сообщения, переведённые на три языка, которых никто никогда не прочитает. Ровно
тот зелёный тест, который ничего не доказывает про продукт.

Настоящая же дыра на этом экране — не пустота, а **неполнота**, и она из того
самого разряда, который эталон велит различать: «нет данных» против «не
загрузилось». Список людей собирается из выданных ролей (`_people`, внутреннее
соединение с `roles`), поэтому человек без единой роли в нём не появляется
вовсе. Молча это читается как «такого человека в системе нет».

Поэтому здесь проверяется два утверждения: что недостижимость пустоты — правда
(иначе объяснение выше стало бы отговоркой), и что про неполноту сказано словами.
"""
from __future__ import annotations

import re

from conftest import body, login_as


def people_table(html: str) -> str:
    """Вторая таблица экрана — «У кого какая роль»."""
    parts = html.split("У кого какая роль", 1)
    assert len(parts) == 2, "на экране нет таблицы людей"
    return parts[1]


def test_the_viewer_is_always_in_the_list_so_it_is_never_empty(client):
    """Пустой этот список быть не может: смотрящий в нём и есть.

    Это утверждение — основание, по которому у экрана нет пустого состояния.
    Если оно однажды перестанет быть верным (например, право начнут выдавать
    не членством), тест покраснеет, и пустое состояние придётся написать.
    """
    login_as(client, "admin")
    try:
        shown = people_table(body(client.get("/roles/")))
        rows = re.findall(r"<tr>", shown)
        assert rows, "список людей пуст — значит пустое состояние всё-таки нужно"
    finally:
        client.post("/logout/")


def test_the_screen_says_that_people_without_roles_are_not_listed(client):
    """Неполнота названа словами, а не оставлена на догадку.

    Человек, у которого ролей нет, в список не попадает. Не сказать об этом —
    значит показать неполный список как полный.
    """
    login_as(client, "admin")
    try:
        html = body(client.get("/roles/"))
        assert "кому уже выдана хотя бы одна роль" in html, (
            "экран не говорит, что показывает только тех, у кого роли есть"
        )
    finally:
        client.post("/logout/")
